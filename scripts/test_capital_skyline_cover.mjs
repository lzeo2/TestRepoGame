import assert from 'node:assert/strict';
import {createSkylineJob} from '../Games/Capital Drive/skyline-job.js';
import {createSkylineCover} from '../Games/Capital Drive/skyline-cover.js';
import {createSimulation} from '../Games/Capital Drive/simulation.js';
import {createShotObstacles} from '../Games/Capital Drive/shot-obstacles.js';

const map={bounds:{minX:-2000,maxX:2000,minZ:-2000,maxZ:2000},spawn:{x:0,z:0,yaw:0},roads:[],buildings:[],areas:[]};
const job=createSkylineJob({site:{x:320,z:290,yaw:.4},groundHeightAt:()=>12});
const simulation=createSimulation(map,{trafficCount:0});
const options={heightAt:()=>12,canOccupy:simulation.canOccupy,nearestRoad:simulation.nearestRoad};
const cover=createSkylineCover(job.layout,options);
assert.equal(cover.length,14);assert.equal(new Set(cover.map(part=>part.id)).size,cover.length);
assert.equal(createSkylineCover(job.layout,{...options,canOccupy:()=>false}).length,0);
assert.equal(createSkylineCover(job.layout,{...options,nearestRoad:()=>({distance:1})}).length,0);
const shots=createShotObstacles({...map,barriers:cover},{heightAt:()=>12});
const part=cover[0],ray={x:part.x-5,y:part.y+1,z:part.z,dx:1,dy:0,dz:0,range:10};
assert(simulation.canOccupy(part),'idle cover is absent from the driving simulation');
for(const item of cover)shots.setBarrierDestroyed(item.id,true);
assert.equal(shots.trace(ray),ray.range);
simulation.registerStaticBarriers(cover);
for(const item of cover)shots.setBarrierDestroyed(item.id,false);
assert(!simulation.canOccupy(part,{length:2,width:1.1}),'ATV hull cannot enter cover');
assert(simulation.moveActor({...part},0,0,.45).blocked,'walking collision shares the footprint');
assert(shots.trace(ray)<ray.range,'low shots stop on the cover');
assert.equal(shots.trace({...ray,y:part.y+3}),ray.range,'high shots can pass over cover');
for(const point of [...job.layout.searches,job.layout.safe,job.layout.landing])assert(!simulation.moveActor({...point},0,0,.45).blocked,'objective stays reachable');
simulation.unregisterStaticBarriers(cover);
for(const item of cover)shots.setBarrierDestroyed(item.id,true);
assert(simulation.canOccupy(part));assert.equal(shots.trace(ray),ray.range);
console.log('PASS Skylark cover footprint, road rejection, active vehicle/foot collisions, shot height and teardown');
