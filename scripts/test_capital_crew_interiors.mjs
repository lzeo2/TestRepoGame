import assert from 'node:assert/strict';
import {createCampaignScenes} from '../Games/Capital Drive/campaign-scenes.js';
import {createInteriors} from '../Games/Capital Drive/interiors.js';
import {createInteriorNavigation} from '../Games/Capital Drive/interior-navigation.js';
import {createSimulation} from '../Games/Capital Drive/simulation.js';
import {createCampaignScenesView} from '../Games/Capital Drive/campaign-scenes-view.js';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
const building={id:'shop',type:'retail',height:4,points:[[-6,20],[6,20],[6,34],[-6,34]]};
const store={id:'mapped-shop',buildingId:'shop',name:'Original Grocery',frontage:{x:0,z:20,yaw:0,width:8}};
const map={bounds:{minX:-100,maxX:100,minZ:-100,maxZ:100},buildings:[building],roads:[],landmarks:[],spawn:{x:0,z:10,yaw:0}};
const simulation=createSimulation(map,{trafficCount:0}),rooms=createInteriors(map,{heightAt:()=>3,stores:[store]});
const actor={x:0,z:18.5,yaw:0},entry=rooms.findEntry(actor),outside={...actor},plan=rooms.enter(entry,actor);
assert(plan);const nav=createInteriorNavigation(plan);
const mission={id:'fixture-crew',stage:0,target:{x:0,z:10},companions:['student','corporate','basement']};
const context={mode:'campaign',character:'student',mission,pose:{x:0,z:10,yaw:0},health:100,playerMode:'foot',hostiles:[]};
const crew=createCampaignScenes(map,simulation,{entrances:[entry]});crew.update(context,.1);assert.equal(crew.people.length,2);
const identities=crew.people.map(p=>p.id),victim=crew.people[0];
assert(crew.receiveHit({kind:'shot',targetId:victim.id,from:{x:victim.x+2,z:victim.z},to:{x:victim.x,z:victim.z},damage:13}));
const health=crew.people[0].health;assert.equal(health,87);
assert(crew.enterInterior(plan,entry,outside));
const inside={...context,interior:true,pose:{...plan.spawn,yaw:0}};
for(let i=0;i<180&&!crew.people.every(p=>p.interiorId===plan.id);i++)crew.update(inside,.1);
assert(crew.people.every(p=>p.interiorId===plan.id),'living crew reach actual door or bounded stuck catch-up and enter');
assert.deepEqual(crew.people.map(p=>p.id),identities);assert.equal(crew.people[0].health,health);
for(const p of crew.people)assert(nav.canOccupy(p,.32),'indoor landing clears actual generated furniture and walls');
const frozen=crew.people;crew.update({...inside,paused:true},.1);assert.equal(crew.people,frozen,'pause retains descriptors');
const cop={id:'police:test',mode:'foot',health:100,interiorId:plan.id,x:crew.people[0].x,z:crew.people[0].z+1};
for(let i=0;i<15;i++)crew.update({...inside,hostiles:[cop]},.1);
assert(crew.drainEvents().some(event=>event.interiorId===plan.id),'same-room officer receives a real bounded ally shot');
for(let i=0;i<15;i++)crew.update({...inside,hostiles:[{...cop,interiorId:null}]},.1);
assert.equal(crew.drainEvents().length,0,'outside officer cannot be shot across a room boundary');
for(let i=0;i<15;i++)crew.update({...inside,attacksAllowed:false,hostiles:[cop]},.1);
assert.equal(crew.drainEvents().length,0,'protected work suppresses attacks');
const scene=new THREE.Scene(),view=createCampaignScenesView(scene,()=>0);
view.update(crew.people,inside.pose);assert.equal(view.stats.people,0,'outdoor batches exclude indoor bodies');
view.update(crew.people,inside.pose,{interiorId:plan.id});assert.equal(view.stats.people,2);
crew.leaveInterior();
for(let i=0;i<300&&crew.people.some(p=>p.interiorId);i++)crew.update(context,.1);
assert(crew.people.every(p=>!p.interiorId),'crew physically walk room exit and return to checked exterior');
assert.equal(crew.roomStats,null,'empty exited room releases navigation');assert.equal(crew.people[0].health,health);
assert.deepEqual(crew.people.map(p=>p.id),identities);
crew.update({...context,recovering:true},.1);assert.equal(crew.people.length,0);assert.equal(crew.roomStats,null);
const distant=createCampaignScenes(map,simulation,{entrances:[entry]});
distant.update({...context,pose:{x:-70,z:0,yaw:0}},.1);
const distantIds=distant.people.map(p=>p.id);assert.equal(distantIds.length,2);
assert(distant.enterInterior(plan,entry,outside));
distant.update(inside,.1);
assert(distant.people.every(p=>p.interiorId===plan.id&&nav.canOccupy(p,.32)),'distant living crew use bounded checked indoor catch-up');
assert.deepEqual(distant.people.map(p=>p.id),distantIds);assert.equal(distant.people.length,2,'catch-up creates no duplicate bodies');
distant.dispose();
view.dispose();crew.dispose();
console.log('Capital crew interiors PASS: actual generated clearance, doorway follow, room-bound combat/rendering, protection, pause, retained identity/health and swept exit cleanup');
