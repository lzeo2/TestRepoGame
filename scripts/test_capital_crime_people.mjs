import assert from 'node:assert/strict';
import {createInteriorPeople} from '../Games/Capital Drive/interior-people.js';
import {createInteriors} from '../Games/Capital Drive/interiors.js';
import {createPedestrians} from '../Games/Capital Drive/pedestrians.js';
import {createInteriorPeopleView} from '../Games/Capital Drive/interior-people-view.js';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';

const map={bounds:{minX:-500,maxX:500,minZ:-300,maxZ:300},roads:[{id:'r',name:'Public Road',width:8,type:'residential',points:[[-450,0],[450,0]]}],
  buildings:[],areas:[],landmarks:[],spawn:{x:0,z:-30,yaw:0}};
const pedestrians=createPedestrians(new THREE.Scene(),map,()=>0);
const original=pedestrians.snapshot(),victim=original[0];
const attack=p=>({x:p.x,z:p.z+1,yaw:0,range:1.25,damage:10,kind:'melee'});
assert.equal(pedestrians.getCrimeTarget(null),null);
assert.equal(pedestrians.getCrimeTarget('ped:1000'),null);
assert.equal(pedestrians.getCrimeTarget('nonsense'),null);
assert.equal(pedestrians.getCrimeTarget(victim.id).id,`ped:${victim.id}`);
assert.equal(pedestrians.strike({...attack(victim),hasLineOfSight:()=>false}).hits,0);
assert.equal(pedestrians.strike({...attack(victim),yaw:Math.PI}).hits,0);
assert(!pedestrians.getCrimeTarget(victim.id).threatened,'occluded swing cannot intimidate');
pedestrians.strike(attack(victim));
assert.equal(pedestrians.getCrimeTarget(victim.id).health,90);
assert(pedestrians.getCrimeTarget(`ped:${victim.id}`).threatened);
assert(!pedestrians.getCrimeTarget(original[1].id).threatened,'a different adult is not tagged as punched');
assert.equal(pedestrians.strike(attack(victim)).hits,0,'same-frame melee deduplicates');
const mug={type:'mugging',targetId:`ped:${victim.id}`,phase:'intimidation',progress:.1,elapsed:.4};
pedestrians.setCrime(mug);pedestrians.update(attack(victim),.1);
assert.equal(pedestrians.snapshot()[0].crimePhase,'intimidation');
assert.equal(pedestrians.snapshot()[0].stopped,true);
assert(pedestrians.snapshot().slice(1).every(p=>p.crimePhase===null),'only the bound victim complies');
let frozen=pedestrians.snapshot();pedestrians.update(attack(victim),0);assert.deepEqual(pedestrians.snapshot(),frozen);
for(const phase of ['emptying','handover']) {
  pedestrians.setCrime({...mug,phase});pedestrians.update(attack(victim),.1);
  assert.equal(pedestrians.snapshot()[0].crimePhase,phase);
}
assert(!pedestrians.drainEvents().some(e=>e.type==='retaliation'),'an active surrender does not also punch the player');
pedestrians.setCrime(null);
for(let i=0;i<125;i++)pedestrians.update({x:0,z:-250},.1);
assert(!pedestrians.getCrimeTarget(victim.id).threatened,'player-hit flag expires on supplied active time');
pedestrians.resetPopulation(map.spawn);
pedestrians.strike({...attack(pedestrians.snapshot()[0]),offenderId:'npc:driver'});
assert(!pedestrians.getCrimeTarget(0).threatened,'NPC assault cannot authorize a player mugging');
pedestrians.resetPopulation(map.spawn);
pedestrians.strike({...attack(pedestrians.snapshot()[0]),damage:100,kind:'firearm'});
pedestrians.setCrime(mug);assert.equal(pedestrians.snapshot()[0].crimePhase,null,'zero-health targets cannot comply');
pedestrians.resetPopulation(map.spawn);assert(!pedestrians.getCrimeTarget(0).threatened);pedestrians.dispose();
assert.equal(pedestrians.getCrimeTarget(0),null);

const roomMap={buildings:[{id:'retail',type:'retail',height:4,points:[[-12,0],[12,0],[12,30],[-12,30]]}]};
const interiors=createInteriors(roomMap,{heightAt:()=>2,stores:[{id:'fictional-store',buildingId:'retail',name:'Example Shop',frontage:{x:0,z:0,yaw:.4,width:8}}]});
const entry=interiors.entries[0],plan=interiors.enter(entry,{x:entry.x,z:entry.z,yaw:.4,y:2});
const people=createInteriorPeople();people.load(plan);
const employee=people.snapshot().find(p=>p.role==='shopkeeper'),customer=people.snapshot().find(p=>p.role==='customer');
assert(employee && customer,'real authored shop plan has employee and customer');
const employeeBefore=people.getCrimeTarget(employee.id);
assert.equal(employeeBefore.kind,'employee');assert.equal(employeeBefore.storeId,'fictional-store');assert.equal(employeeBefore.roomId,plan.id);
assert.equal(people.getCrimeTarget(customer.id),null,'a customer cannot stand in for the till employee');
assert.equal(people.strike({...attack(employee),hasLineOfSight:()=>false}).hits,0);
assert.equal(people.strike({...attack(employee),z:employee.z+10}).hits,0,'distant punches cannot hit room employees');
assert.equal(people.strike({...attack(employee),yaw:Math.PI}).hits,0,'a punch facing away cannot hit behind the player');
assert.equal(people.strike({...attack(employee),damage:NaN}).hits,0);
assert.equal(people.strike(attack(employee)).hits,1);
assert.equal(people.getCrimeTarget(employee.id).health,90);assert(people.getCrimeTarget(employee.id).threatened);
assert.equal(people.strike(attack(employee)).hits,0);
let reports=people.drainEvents();assert.equal(reports.length,1);assert.equal(reports[0].type,'witness');assert.equal(reports[0].offenderId,'player');
assert.deepEqual(people.drainEvents(),[]);
people.alert({x:employee.x,z:employee.z,kind:'gunshot'});assert.deepEqual(people.drainEvents(),[],'pellet/alert witnesses deduplicate the same assault burst');
const robbery={type:'robbery',targetId:employee.id,roomId:plan.id,phase:'intimidation',elapsed:.1,progress:.02};
people.setCrime(robbery);people.update(.1,{actor:attack(employee)});
assert.equal(people.snapshot().find(p=>p.id===employee.id).crimePhase,'intimidation');
assert.equal(people.snapshot().find(p=>p.id===customer.id).crimePhase,null);
const scene=new THREE.Scene(),view=createInteriorPeopleView(scene,()=>2);view.load(plan);
const poses=[];
for(const phase of ['intimidation','emptying','handover']) {
  people.setCrime({...robbery,phase});people.update(.1,{actor:attack(employee)});view.update(people.snapshot(),.1);
  assert.equal(view.stats.geometryCount,6);assert.equal(view.stats.materialCount,1);assert(view.stats.drawCalls<=6);
  const root=scene.children[0];assert.equal(root.children.length,6);
  for(const mesh of root.children)assert(mesh.instanceMatrix.array.every(Number.isFinite));
  poses.push([...root.children[4].instanceMatrix.array]);
  if(phase==='handover')assert(root.children[5].count>=2,'employee apron and handed-over bag reuse the existing prop batch');
}
assert.notDeepEqual(poses[0],poses[1],'hands-up and till reach have distinct arm transforms');
assert.notDeepEqual(poses[1],poses[2],'handover extends arms with the bag');
frozen=people.snapshot();const matrices=scene.children[0].children.map(mesh=>[...mesh.instanceMatrix.array]);
people.update(0,{actor:attack(employee)});view.update(people.snapshot(),0);
assert.deepEqual(people.snapshot(),frozen,'pause freezes health, fear and hit clocks');
assert.deepEqual(scene.children[0].children.map(mesh=>[...mesh.instanceMatrix.array]),matrices,'paused authoritative pose stays fixed');
people.setCrime(null);for(let i=0;i<125;i++)people.update(.1);
assert(!people.getCrimeTarget(employee.id).threatened);
people.clear();assert.equal(people.getCrimeTarget(employee.id),null);assert.deepEqual(people.drainEvents(),[]);
people.load(plan);assert.equal(people.getCrimeTarget(employee.id).health,100);assert(!people.getCrimeTarget(employee.id).threatened);
people.strike({...attack(employee),damage:100,kind:'firearm'});people.setCrime(robbery);
assert.equal(people.getCrimeTarget(employee.id).health,0);assert.equal(people.snapshot().find(p=>p.id===employee.id).crimePhase,null);
assert.equal(people.strike({...attack(employee),damage:100,kind:'firearm'}).hits,0,'repeated pellets cannot hit a defeated employee');
view.update(people.snapshot(),.1);assert(view.stats.drawCalls<=6);
people.clear();view.clear();view.dispose();assert.equal(scene.children.length,0);
console.log('PASS live street/employee targets, attributed LOS strikes and pellet witnesses, expiring punched threat, target-only compliance, supplied phases, zero-health rejection, paused six-batch poses/bag and room reset');
