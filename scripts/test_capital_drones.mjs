import assert from 'node:assert/strict';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
import { createDrone } from '../Games/Capital Drive/drone.js';
import { createDroneView } from '../Games/Capital Drive/drone-view.js';

const body={mode:'foot',health:100,actor:{x:0,z:0,yaw:0},missionClock:17};
const original=JSON.stringify(body), ctx={owned:true};
const drone=createDrone({heightAt:()=>10});
assert.equal(drone.deploy(body),false,'ownership is explicit');
for(const invalid of [{...body,mode:'vehicle'},{...body,health:0},{...body,recovery:{}},{...body,interiorId:'shop'},{...body,actor:{x:NaN,z:0}}]) {
  assert.equal(drone.deploy(invalid,ctx),false,'actual living exterior foot body required');
}
assert.equal(drone.deploy(body,{...ctx,paused:true}),false);
assert.equal(drone.deploy(body,ctx),true);
assert.equal(drone.deploy(body,ctx),false,'cannot reset battery while flying');
assert.equal(drone.snapshot().y,13);
const initial=drone.snapshot();
for(const dt of [0,-1,NaN,Infinity]) drone.step(dt,{body,forward:1});
drone.step(2,{body,forward:1,paused:true});
assert.deepEqual(drone.snapshot(),initial,'only supplied active finite time advances');
drone.step(1,{body,forward:1});
assert.equal(drone.snapshot().z,-9);
assert.equal(drone.snapshot().battery,89);
drone.step(10,{body,lift:1});
assert.equal(drone.snapshot().altitude,45);
drone.step(10,{body,lift:-1});
assert.equal(drone.snapshot().altitude,3);
drone.step(30,{body,forward:1});
assert(drone.snapshot().range<=150+1e-9);
assert(Object.isFrozen(drone.snapshot()));
assert.equal(JSON.stringify(body),original,'flight never moves, heals or advances body mission clocks');
assert.equal(drone.recall(),true);
assert.equal(drone.snapshot().active,false);
assert.equal(drone.deploy(body,{sandbox:true}),true);
drone.step(95,{body});
assert.equal(drone.snapshot().battery,0);
assert.equal(drone.snapshot().reason,'battery-empty');
assert.equal(drone.snapshot().active,false);
assert.equal(drone.deploy(body,ctx),true);
drone.step(.1,{body:{...body,recovery:{}}});
assert.equal(drone.snapshot().reason,'body-unavailable');
assert.equal(drone.deploy(body,ctx),true);
drone.step(.1,{body,interiorId:'room'});
assert.equal(drone.snapshot().active,false,'interior transitions recall');
const blocked=createDrone({canOccupy:(p,{from})=>!(p.z< -2 && from.z>=-2)});
assert(blocked.deploy(body,ctx));
blocked.step(2,{body,forward:1,right:1});
assert(blocked.snapshot().z>=-2,'swept half-metre probes stop a crossed wall');
assert(blocked.snapshot().x>5,'free axis slides along cover');
const badGround=createDrone({heightAt:()=>NaN});
assert.equal(badGround.deploy(body,ctx),false,'invalid terrain cannot create a nonfinite flight');
const scene=new THREE.Scene(), view=createDroneView(scene), mesh=scene.children[0];
assert.equal(view.stats.drawCalls,0);
const finiteDrone=createDrone(); assert(finiteDrone.deploy(body,ctx));
view.update(finiteDrone.snapshot());
assert.equal(view.stats.drawCalls,1); assert(view.stats.triangles<1000);
assert.equal(mesh.position.y,3);
const geometry=mesh.geometry, material=mesh.material;
for(const attribute of Object.values(geometry.attributes)) assert([...attribute.array].every(Number.isFinite));
let geometryDisposals=0,materialDisposals=0;
geometry.addEventListener('dispose',()=>geometryDisposals++); material.addEventListener('dispose',()=>materialDisposals++);
for(let i=0;i<100;i++)view.update(finiteDrone.snapshot());
assert.equal(mesh.geometry,geometry); assert.equal(mesh.material,material);
finiteDrone.recall(); view.update(finiteDrone.snapshot()); assert.equal(view.stats.visible,0);
view.update({active:true,x:NaN,y:3,z:0,yaw:0}); assert.equal(view.stats.visible,0);
view.dispose(); view.dispose(); assert.equal(scene.children.length,0);
assert.equal(geometryDisposals,1); assert.equal(materialDisposals,1);
assert.equal(view.stats.meshes,0); assert.equal(view.stats.triangles,0);
drone.dispose(); drone.dispose(); assert.equal(drone.deploy(body,ctx),false);
console.log('Capital drone guards, supplied-time flight, collision, body isolation and pooled resources passed');
