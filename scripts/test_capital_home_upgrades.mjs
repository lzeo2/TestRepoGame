import assert from 'node:assert/strict';
import {createProgression} from '../Games/Capital Drive/progression.js';
import {createHouseController} from '../Games/Capital Drive/house-controller.js';
const map={spawn:{x:0,z:0},storyHomes:{basement:{roomId:'house-home'}}};
const homes=[{id:'house-home',type:'house',name:'Fixture',x:0,z:0,yaw:0},{id:'house-other',type:'house',name:'Fixture',x:0,z:0,yaw:0}];
const ctx={pose:{x:0,z:0},onFoot:true,health:45,vehicleHealth:100,wanted:0,respawnSerial:0,sandbox:false,mode:'street',interior:{roomId:'house-home'}};
let receipt=null;
const p=createProgression(map,null,{homes,takeSafehouseRest:()=>receipt});
assert.equal(p.homeStatus('house-other','street'),null);
for(const bad of [{...ctx,sandbox:true},{...ctx,paused:true},{...ctx,busy:true},{...ctx,interior:{roomId:'house-other'}}])assert.equal(p.buyHomeUpgrade('house-home','pantry',bad).ok,false);
assert(p.buyHomeUpgrade('house-home','pantry',ctx).ok);assert.equal(p.state.cash,820);
assert.equal(p.buyHomeUpgrade('house-home','pantry',ctx).ok,false);
assert.equal(p.buyHomeUpgrade('house-home','refill',ctx).ok,false);
let health=45,saves=0;
const c=createHouseController({progression:p,getPlan:()=>({id:'house-home',type:'house'}),save:()=>saves++,heal:value=>health=Math.min(100,health+value)});
assert(c.usePantry('house-home',{...ctx,health}).ok);assert.equal(health,75);
assert(c.usePantry('house-home',{...ctx,health}).ok);assert.equal(health,100);
assert.equal(c.usePantry('house-home',{...ctx,health}).ok,false);assert.equal(saves,2);
health=50;assert(c.usePantry('house-home',{...ctx,health}).ok);
assert.equal(p.homeStatus('house-home','street').meals,0);assert.equal(c.usePantry('house-home',ctx).ok,false);
assert(p.buyHomeUpgrade('house-home','refill',ctx).ok);assert.equal(p.state.cash,790);
assert(p.buyHomeUpgrade('house-home','comfort',ctx).ok);assert.equal(p.state.cash,340);
receipt=Object.freeze({roomId:'house-home',outcome:'rested',serial:1});
assert(p.restSafehouse('house-home',ctx).ok);assert.equal(p.state.cash,340);
assert.equal(p.restSafehouse('house-home',ctx).ok,false,'free rest still needs a fresh completed bed receipt');
const saved=p.serialize(),loaded=createProgression(map,saved,{homes});
assert.deepEqual(loaded.homeStatus('house-home','street'),p.homeStatus('house-home','street'));
assert.deepEqual(createProgression(map,null,{homes}).homeStatus('house-home','street').meals,0,'fresh mode has no pantry');
assert.equal(loaded.homeStatus('house-home','campaign').comfort,false,'home improvements stay isolated between game modes');
assert.equal(p.buyHomeUpgrade('house-home','pantry',{...ctx,mode:'sandbox'}).ok,false);
for(const value of [{comfort:true,pantry:false,meals:3},{comfort:true,pantry:true,meals:4}])assert.throws(()=>createProgression(map,{...saved,homeUpgrades:{street:{'house-home':value}}},{homes}),/home upgrades/);
assert.throws(()=>createProgression(map,{...saved,homeUpgrades:{street:{'house-other':saved.homeUpgrades.street['house-home']}}},{homes}),/home upgrades/);
console.log('Capital home improvements: contextual purchases, meal healing and refill, free receipt-backed rest, save roundtrip and corrupt-save guards passed');
