import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
import {ANU_CAMPUS} from '../Games/Capital Drive/anu-campus-data.js';
import {applyAnuCampus,anuBridgeHeightAt} from '../Games/Capital Drive/anu-campus.js';
import {createAnuCampusView} from '../Games/Capital Drive/anu-campus-view.js';
const map=JSON.parse(await readFile(new URL('../Games/Capital Drive/data/canberra-north.json',import.meta.url),'utf8'));
const before=JSON.stringify(map),result=applyAnuCampus(map);
assert.equal(result.buildings,map.buildings);assert.equal(result.roads,map.roads);
assert.equal(result.regionalPlaces.length,6);assert.equal(result.landmarkBuildingIds.length,6);
assert.equal(result.landmarks.length,map.landmarks.length+9);
assert.equal(result.areas.length,map.areas.length+1);
assert.equal(applyAnuCampus(result),result,'idempotent composition');
assert.throws(()=>applyAnuCampus({...map,buildings:[]}),/Missing retained/);
assert.throws(()=>applyAnuCampus({...map,meta:{origin:[0,0]}}),/projection/);
assert.equal(JSON.stringify(map),before);
assert.equal(ANU_CAMPUS.pedestrianPaths.length,5);
assert.deepEqual(ANU_CAMPUS.lawn.points[0],ANU_CAMPUS.lawn.points.at(-1));
for(const path of ANU_CAMPUS.pedestrianPaths){assert.equal(path.nodes.length,path.points.length);assert.equal(path.sourceTags.highway,'pedestrian');assert(path.sourceVersion>0);}
const bridge=ANU_CAMPUS.pedestrianPaths.find(p=>p.layer===1),[a,b]=bridge.points;
const height=(x,z)=>100+x*.001+z*.002;
assert.equal(anuBridgeHeightAt(0,0,height),null);
assert(Math.abs(anuBridgeHeightAt((a[0]+b[0])/2,(a[1]+b[1])/2,height)-(height(...a)+height(...b))/2-.06)<1e-8);
const scene=new THREE.Scene(),view=createAnuCampusView(scene,height);
assert.equal(scene.children.length,1);assert.equal(scene.children[0].children.length,2);
const avenue=scene.getObjectByName('University Avenue pedestrian source spans'),tile=avenue.material.map;
assert.equal(tile.image.width,64);assert.equal(tile.image.data.length,64*64*4);
assert.equal(tile.generateMipmaps,true);assert.equal(tile.wrapS,THREE.RepeatWrapping);
assert.equal(avenue.geometry.attributes.uv.count,avenue.geometry.attributes.position.count);
let tileDisposed=0;tile.addEventListener('dispose',()=>tileDisposed++);
assert(view.stats().triangles<100,'source paving/lawn stays tiny');
scene.traverse(o=>{if(o.isMesh)assert(o.geometry.attributes.position.array.every(Number.isFinite));});
view.update({x:0,z:0});assert.equal(view.stats().draws,0);
view.update({x:-1480,z:-4500});assert.equal(view.stats().draws,2);
let disposed=0;scene.traverse(o=>{if(o.isMesh)o.geometry.addEventListener('dispose',()=>disposed++);});
view.dispose();view.dispose();assert.equal(disposed,2);assert.equal(tileDisposed,1);assert.equal(scene.children.length,0);
console.log('PASS ANU: six retained footprint guards, nine pins, five source pedestrian spans, mapped lawn, estimated bridge support, two bounded draws and idempotent disposal.');
