import assert from 'node:assert/strict';
import {createWatercraft,WATERCRAFT_OFFERS} from '../Games/Capital Drive/watercraft.js';
const ring=[[0,0],[1000,0],[1000,1000],[0,1000],[0,200],[0,100],[0,0]];
const map={areas:[{id:'lake',sourceId:'relation/3400115',type:'water',points:ring}],roads:[{id:'road',name:'Menindee Drive',type:'residential',points:[[-10,100],[-10,200]]}]};
let queries=0,blockedExit=false;
const water=Object.freeze({id:'lake',y:5.93});
const waterAt=(x,z)=>{queries++;return x>0&&x<1000&&z>0&&z<1000&&!(x>=100&&x<=120&&z>=80&&z<=120)?water:null;};
const owned=new Set(),simulation={waterAt,moveActor:()=>({blocked:false})};
const game=createWatercraft(map,simulation,{owns:kind=>owned.has(kind),heightAt:()=>8,canExit:()=>!blockedExit});
assert(game.dock);assert.equal(game.dock.name,'Boat Shed');assert.equal(game.dock.roadId,'road');
assert.equal(game.dock.sourceId,'relation/3400115');assert(!waterAt(game.dock.x,game.dock.z));
assert.equal(game.snapshot().crafts.length,2);assert.equal(game.vehicles.length,2);
const ctx={valid:true,onFoot:true,pose:game.dock.shore};
assert(!game.board('watercraft:boat',ctx).ok,'ownership callback is required');
owned.add('boat');owned.add('jet-ski');
for(const invalid of [{valid:false},{onFoot:false},{indoors:true},{recovering:true},{pose:{x:900,z:900}}])assert(!game.board('watercraft:boat',{...ctx,...invalid}).ok);
assert(game.board('watercraft:boat',ctx).ok);assert.equal(game.active.kind,'boat');assert(game.seatPose);
let before=game.snapshot();game.step(.1,{throttle:1},{valid:true,paused:true});assert.deepEqual(game.snapshot(),before);
game.step(0,{throttle:1},{valid:true});assert.deepEqual(game.snapshot(),before);
assert.throws(()=>game.step(-1,{},{}),/finite/);
for(let i=0;i<220;i++)game.step(.1,{throttle:1},{valid:true});
assert(game.active.x<100-WATERCRAFT_OFFERS[0].length/2+.35,'forward hull sweep stops before the island');
assert.equal(game.active.speed,0);assert(waterAt(game.active.x,game.active.z));
blockedExit=true;before=game.snapshot();assert(!game.dismount({valid:true}).ok);assert.deepEqual(game.snapshot(),before,'failed exit leaves occupancy/pose intact');
blockedExit=false;const exit=game.dismount({valid:true});assert(exit.ok);assert.equal(exit.swimming,!!waterAt(exit.pose.x,exit.pose.z));assert.equal(game.active,null);
game.reset();Object.assign(game.vehicles[0],{x:200,z:200});assert(game.board('watercraft:boat',{...ctx,pose:{x:200,z:200}}).ok);
const swimmingExit=game.dismount({valid:true});assert(swimmingExit.ok&&swimmingExit.swimming);
game.reset();assert(game.board('watercraft:boat',ctx).ok);
for(let i=0;i<20;i++)game.step(.1,{throttle:1},{valid:true});
const boatSpeed=game.active.speed;assert(!game.dismount({valid:true}).ok,'moving exit is denied');
game.reset();assert(game.board('watercraft:jet-ski',ctx).ok);
for(let i=0;i<20;i++)game.step(.1,{throttle:1},{valid:true});
assert(game.active.speed>boatSpeed*1.5,'jet ski has materially stronger acceleration');
game.reset();assert(game.board('watercraft:boat',ctx).ok);
for(let i=0;i<200;i++)game.step(.1,{throttle:-1},{valid:true});
assert(game.active.x>=WATERCRAFT_OFFERS[0].length/2,'reverse sweep cannot cross the shoreline');
assert.equal(game.active.speed,0);
const firstSeat=game.seatPose;assert.equal(game.seatPose,firstSeat,'unchanged seat pose is cached');assert.equal(firstSeat.speed,game.active.speed);assert(game.isActive);
assert.equal(game.step(0,{},ctx),undefined,'step never builds a returned snapshot');
const stableFleet=game.vehicles;game.reset();assert.equal(game.vehicles,stableFleet);
const snapshot=game.snapshot();snapshot.dock.x=999;assert.notEqual(game.dock.x,999,'dock snapshots are detached');
assert(Object.isFrozen(snapshot)&&Object.isFrozen(snapshot.crafts[0]));
game.dispose();assert.equal(game.active,null);assert(!game.board('watercraft:boat',ctx).ok);assert.equal(game.nearest(ctx.pose),null);
const none=createWatercraft({areas:[],roads:[]},simulation);assert.equal(none.dock,null);assert.equal(none.snapshot().crafts.length,0);
console.log(`PASS watercraft: source-derived dry dock; purchase gate; distinct boat/jet handling; lake/island/shore swept hulls; pause; valid boarding; moving/blocked/safe swimming exits; fixed two craft; immutable snapshots; disposal. Water probes ${queries}.`);
