import assert from 'node:assert/strict';
import {createSkillTrees,sanitizeSkillSave} from '../Games/Capital Drive/skill-trees.js';
const ctx={mode:'street',crewPresent:true};
const tree=createSkillTrees();
assert.equal(tree.purchase('player','second-wind',ctx).ok,false);
for(const extra of [{mode:'free'},{sandbox:true},{preview:true},{paused:true},{recovering:true}])assert.equal(tree.award({kind:'job',id:'test',success:true},{...ctx,...extra}),false);
assert.equal(tree.award({kind:'job',id:'test',success:false},ctx),false);
assert.equal(tree.award({kind:'idle',id:'test',success:true},ctx),false);
assert.equal(tree.award({kind:'job',id:'test',success:true},ctx),true);
assert.equal(tree.award({kind:'job',id:'test',success:true},ctx),false);
assert.equal(tree.purchase('player','steady-stride',ctx).ok,true);
assert.equal(tree.effects(ctx).footSpeed,1.05);
assert.equal(tree.effects({mode:'free'}).footSpeed,1);
assert.equal(tree.purchase('player','steady-stride',ctx).ok,false);
assert.equal(tree.purchase('crew','keep-pace',ctx).ok,true);
const restored=createSkillTrees(tree.serialize());
assert.equal(restored.award({kind:'job',id:'test',success:true},ctx),false,'reload cannot farm receipt');
for(let i=0;i<120;i++)restored.award({kind:'work',id:`station-${i}`,success:true},ctx);
assert.equal(restored.describe('player').earned,12);
assert.equal(restored.serialize().receipts.length,96);
for(const track of ['player','crew'])for(const id of restored.describe(track).nodes.map(node=>node.id))if(!restored.describe(track).nodes.find(node=>node.id===id).unlocked)assert.equal(restored.purchase(track,id,ctx).ok,true);
assert.deepEqual(restored.effects(ctx),{footSpeed:1.05,recoveryDuration:.8,repairAmount:10,workReward:1.2,crewRegroup:1.15,crewRetry:.7,crewFormation:.75,crewWorkReward:1.15});
assert.equal(restored.effects({...ctx,crewPresent:false}).crewWorkReward,1);
assert.deepEqual(sanitizeSkillSave({version:1,player:{earned:1,unlocked:['second-wind','__proto__']},crew:{earned:Infinity,unlocked:['keep-pace']},receipts:['bad','job:okay']}),{version:1,player:{earned:1,unlocked:[]},crew:{earned:0,unlocked:[]},receipts:['job:okay']});
const detached=restored.serialize();detached.player.unlocked=[];
assert.equal(restored.effects(ctx).footSpeed,1.05);
const solo=createSkillTrees();solo.award({kind:'mission',id:'solo',success:true},{mode:'campaign'});assert.equal(solo.describe('crew').earned,0);
console.log('Capital skill trees: branches, effects, isolation, bounded saves and receipt dedupe passed.');
// Learned movement and recovery reach the actual gameplay rules.
const {createSimulation}=await import('../Games/Capital Drive/simulation.js');
const {createGameplay}=await import('../Games/Capital Drive/gameplay.js');
const map={bounds:{minX:-500,maxX:500,minZ:-500,maxZ:500},roads:[{id:'main',points:[[-400,0],[400,0]],nodes:[1,2],width:12,speed:40}],buildings:[],spawn:{x:0,z:0,yaw:0},landmarks:[]};
const move=effects=>{
  const sim=createSimulation(map,{trafficCount:0}),game=createGameplay(map,sim,{skillEffects:()=>effects});
  game.interact();const start={...game.state.actor};
  for(let i=0;i<60;i++)game.step(1/60,{moveZ:-1});
  return {game,distance:Math.hypot(game.state.actor.x-start.x,game.state.actor.z-start.z)};
};
const base=move({}),trained=move(restored.effects(ctx));
assert.ok(Math.abs(trained.distance/base.distance-1.05)<.002,'learned stride changes real walking distance by five percent');
base.game.state.health=0;trained.game.state.health=0;base.game.step(1/60,{});trained.game.step(1/60,{});
assert.equal(base.game.state.recovery.duration,3.4);
assert.equal(trained.game.state.recovery.duration,3.4*.8);
console.log('Capital skill trees: actual walking distance and medical recovery effects passed.');
