#!/usr/bin/env python3
"""Compile public AWM exterior geometry from the pinned, external north OSM cache.

No download or imagery processing. Geometry is ODbL; facade detail is original
architectural interpretation. Run with --source-cache pointing at the north cache.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_FILE = 'osm-map-3-2.json'
SOURCE_HASH = '472a108371afbdcaa9c0427d0321b4eff9f4892316a6e56d4fd4fc424c5dc335'
SOURCE_URL = 'https://api.openstreetmap.org/api/0.6/map.json?bbox=149.14350000000002%2C-35.2855%2C149.157%2C-35.27675'
PAVED = [1343905213, 1489603134, 1489603135, 1489603136, 1489603141,
         1489603142, 1489603154, 1489603155, 1489603156, 1489430294]
LAWNS = [1489603112, 1489603113, 1489603114, 1489603115, 1489603116,
         1489603117, 1489603118, 1489603119, 1489603120, 1489603121,
         1489603122, 1489603123, 1489603124, 1489603125, 1489603126,
         1489603127, 1489603128, 1489603129, 1489603153]
PATHS = [1489603143, 1489603144, 1489603145, 1489603146, 1489603147,
         1489603148, 1489603149, 1489603150, 1489603132, 1489603133]


def build(cache):
    raw = (cache / SOURCE_FILE).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_HASH:
        raise ValueError('War Memorial north snapshot hash differs from pinned source')
    elements = json.loads(raw)['elements']
    nodes = {e['id']: e for e in elements if e['type'] == 'node'}
    ways = {e['id']: e for e in elements if e['type'] == 'way'}
    relation = next(e for e in elements if e['type'] == 'relation' and e['id'] == 7527080)
    assert [(m['ref'], m['role']) for m in relation['members']] == [(5090724, 'outer'), (520199710, 'inner')]
    mx = 111320 * math.cos(math.radians(-35.318))

    def feature(identity):
        way = ways[identity]
        tags = way.get('tags', {})
        return {'sourceId': f'way/{identity}', 'version': way['version'],
                'sourceTimestamp': way['timestamp'],
                'sourceUrl': f'https://www.openstreetmap.org/way/{identity}',
                'points': [[round((nodes[n]['lon'] - 149.137) * mx, 2),
                            round((-35.318 - nodes[n]['lat']) * 111320, 2)] for n in way['nodes']],
                'sourceTags': {k: tags[k] for k in ('name', 'height', 'roof:height', 'roof:shape',
                              'roof:colour', 'roof:material', 'building:colour', 'highway', 'area', 'area:highway',
                              'landuse', 'surface') if k in tags}}

    main, courtyard, tower, dome = [feature(i) for i in (5090724, 520199710, 520199707, 520199676)]
    return {'id': 'australian-war-memorial', 'name': 'Australian War Memorial',
            'x': 1085.71, 'z': -4164.17, 'radius': 175, 'origin': [149.137, -35.318],
            'source': {'attribution': '© OpenStreetMap contributors', 'license': 'ODbL-1.0',
                       'licenseUrl': 'https://opendatacommons.org/licenses/odbl/1-0/',
                       'attributionUrl': 'https://www.openstreetmap.org/copyright',
                       'file': SOURCE_FILE, 'sha256': SOURCE_HASH, 'url': SOURCE_URL,
                       'relationId': 'relation/7527080', 'reviewedDate': '2026-11-22'},
            'interpretation': 'Original exterior only. Source plan rings and tagged heights; sandstone facade relief, copper-toned dome, cornices and terraces are estimates, not surveyed or imagery-derived detail. Public ground follows the existing terrain; no interior, security or access model.',
            'main': main, 'courtyard': courtyard, 'tower': tower, 'dome': dome,
            'paved': [feature(i) for i in PAVED], 'lawns': [feature(i) for i in LAWNS],
            'paths': [feature(i) for i in PATHS]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-cache', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT / 'Games/Capital Drive/war-memorial-data.js')
    args = parser.parse_args()
    data = build(args.source_cache)
    body = '// Generated by scripts/build_capital_war_memorial.py; public OSM exterior only.\n'
    body += 'function freeze(value) { if(value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; }\n'
    body += 'export const WAR_MEMORIAL_DATA = freeze(' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ');\n'
    args.output.write_text(body)
    print(f'War Memorial: {len(data["main"]["points"])} outline points; {len(PAVED)} public paved polygons; {len(LAWNS)} lawn polygons; {len(PATHS)} paths; {len(body.encode())} bytes')


if __name__ == '__main__':
    main()
