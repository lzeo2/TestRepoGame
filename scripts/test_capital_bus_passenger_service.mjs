import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createBuses } from '../Games/Capital Drive/buses.js';
import { createSimulation } from '../Games/Capital Drive/simulation.js';
import { applyMapExpansion } from '../Games/Capital Drive/map-expansion.js';
import { applyRoadProfiles } from '../Games/Capital Drive/road-network.js';
import { BUS_STOPS } from '../Games/Capital Drive/street-assets.js';

const data = async name => JSON.parse(await readFile(new URL(`../Games/Capital Drive/data/${name}.json`, import.meta.url)));
const map = applyRoadProfiles(applyMapExpansion(await data('canberra'), await data('canberra-north')), await data('road-profiles'));
const simulation = createSimulation(map, { trafficCount: 0 });
simulation.player.active = false;
const buses = createBuses(map, simulation);
simulation.setExternalVehicles(buses.vehicles);
const sourceBefore = JSON.stringify(BUS_STOPS), initial = buses.snapshot();
const advance = seconds => { for (let i = 0; i < Math.ceil(seconds * 10); i++) buses.step(.1); };
assert.equal(buses.tracking(), null);
assert.equal(buses.requestStop().ok, false);
assert.equal(buses.services.length, 2);
assert(Object.isFrozen(buses.services));
for (const service of buses.services) {
  assert(service.fictional && service.stops.length && service.points.length < 120);
  assert(Object.isFrozen(service.points) && Object.isFrozen(service.stops));
  assert.throws(() => { service.points[0].x = NaN; }, TypeError);
  assert(service.stops.every(stop => BUS_STOPS.some(source => source.id === stop.id)));
}
const bus = buses.vehicles[0];
assert(buses.interact({ pose: buses.nearest(bus), onFoot: true }).boarded);
advance(3);
assert(bus.speed > .1);
const before = { x: bus.x, z: bus.z, speed: bus.speed };
const result = buses.interact({ onFoot: true });
assert(result.stopping && !result.ok);
assert.match(result.reason, /Stop requested/);
assert.deepEqual({ x: bus.x, z: bus.z, speed: bus.speed }, before, 'request is not an immediate brake or teleport');
const requested = buses.tracking();
assert(requested.stopRequested && requested.requestedStopId === requested.nextStop.id);
assert(Number.isInteger(requested.distanceToNextStop) && requested.distanceToNextStop > 0);
// A long red light must not expire the passenger request after the old20s hold.
const lights = simulation.trafficLights;
simulation.trafficLights = { stopDistance: () => 0 };
advance(25);
assert.equal(buses.tracking().requestedStopId, requested.requestedStopId);
assert(buses.tracking().stopRequested);
assert.equal(bus.speed, 0);
const paused = buses.snapshot(); buses.step(0); buses.step(NaN);
assert.deepEqual(buses.snapshot(), paused);
simulation.trafficLights = lights;
let ticks = 0;
while (!bus.currentStop && ticks++ < 4500) {
  const previous = { x: bus.x, z: bus.z };
  buses.step(.1);
  assert(Math.hypot(bus.x-previous.x, bus.z-previous.z) <= .721, 'physical travel remains bounded');
}
assert(bus.currentStop, 'requested source platform is physically reached');
assert.equal(bus.currentStop.id, requested.requestedStopId);
const arrival = buses.tracking(), pose = { x: bus.x, z: bus.z }, visits = bus.stopVisits;
assert.equal(arrival.phase, 'arrived');
assert.equal(arrival.distanceToNextStop, 0);
assert(arrival.canExit && arrival.stopRequested);
assert.match(arrival.prompt, /Leave bus/);
advance(15);
assert.deepEqual({ x: bus.x, z: bus.z }, pose, 'requested arrival waits for passenger beyond regular dwell');
assert.equal(bus.stopVisits, visits, 'waiting never emits another arrival');
const occupy = simulation.canOccupy;
simulation.canOccupy = () => false;
assert.equal(buses.tracking().exitBlocked, true);
assert.equal(buses.interact().ok, false);
assert(buses.passenger, 'blocked door never detaches the passenger');
simulation.canOccupy = occupy;
const exit = buses.interact();
assert(exit.exited && exit.stop.id === requested.requestedStopId);
assert(!buses.passenger && buses.tracking() === null);
assert.equal(bus.requestedStopId, null);
advance(12);
assert(Math.hypot(bus.x-pose.x, bus.z-pose.z) > 1, 'normal legal service resumes after exit');
assert.equal(JSON.stringify(BUS_STOPS), sourceBefore);
buses.reset();
assert.deepEqual(buses.snapshot(), initial, 'reset clears request, arrival, distance and passenger');
console.log(`PASS passenger bus service: source-only stops, frozen map services, persistent request through25s red, physical arrival in${ticks}ticks, held arrival, blocked-exit retention, clear dismount, normal resume and pause/reset`);
