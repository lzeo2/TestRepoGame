#!/usr/bin/env python3
"""Check (default) or write Capital Drive's content-addressed offline closure.

Only reachable imports, literal fetch/new URL references, HTML links and CSS URLs
are followed. Vendor loader functions accepting caller-supplied URLs are not an
asset inventory; new runtime assets must use a literal reference to be included.
"""

import argparse
import hashlib
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import quote, unquote, urlsplit


GAME = Path('Games/Capital Drive')
HEADER = '// Generated by scripts/build_capital_cache.py --write; do not edit.\n'
ZERO_BUILD = '000000000000'
INDEX_BUILD = re.compile(rb'(<code id="build-version">)([0-9a-f]{12})(</code>)')
WORKER_BUILD = re.compile(rb"(const buildId = ')([0-9a-f]{12})('; // Generated build ID)")


class ManifestError(ValueError):
    """The static closure cannot be reproduced safely."""


def stamp_build(data, pattern, build, label):
    """Replace only the generated payload, preserving every other runtime byte."""
    if len(list(pattern.finditer(data))) != 1:
        raise ManifestError(f'{label} requires exactly one generated build ID marker')
    return pattern.sub(lambda match: match[1] + build.encode('ascii') + match[3], data)


def seed_hash(seed):
    return hashlib.sha256(json.dumps(seed, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def js_tokens(source):
    """Read identifiers, punctuation and strings, ignoring comments/templates."""
    pattern = re.compile(r'''//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`|[A-Za-z_$][\w$]*|[^\s]''')
    tokens = []
    for match in pattern.finditer(source):
        value = match.group()
        if value.startswith(('//', '/*')):
            continue
        if value[0] in "\"'":
            # URL literals do not need JS escape decoding; reject ambiguous ones.
            if '\\' in value:
                tokens.append(('escaped', value))
            else:
                tokens.append(('string', value[1:-1]))
        else:
            tokens.append(('token', value))
    return tokens


def js_references(source):
    tokens = js_tokens(source)
    references = []
    for i, (kind, value) in enumerate(tokens):
        if kind != 'token' or value not in ('import', 'export', 'fetch', 'new', 'loadGameData', 'GAME_DATA_FILES'):
            continue
        following = tokens[i + 1:] if value in ('import', 'export', 'loadGameData', 'GAME_DATA_FILES') else tokens[i + 1:i + 5]
        if value == 'export' and (not following or following[0][1] not in ('*', '{')):
            continue
        if value in ('import', 'export'):
            if following and following[0][1] == '.':
                continue  # import.meta
            if following and following[0][1] == '(':
                if len(following) < 3 or following[1][0] != 'string' or following[2][1] != ')':
                    raise ManifestError('dynamic imports must use one literal URL')
                references.append(following[1][1])
            elif value == 'import' and following and following[0][0] == 'string':
                references.append(following[0][1])
            else:
                for j, token in enumerate(following):
                    if token[1] == ';':
                        break
                    if token[1] == 'from' and j + 1 < len(following):
                        if following[j + 1][0] != 'string':
                            raise ManifestError('module imports must use a literal URL')
                        references.append(following[j + 1][1])
                        break
        map_literals = None
        if value == 'loadGameData' and len(following) > 2 and following[0][1] == '(' and following[1][1] == '[':
            map_literals = following[2:]
        if value == 'GAME_DATA_FILES' and i and tokens[i - 1] == ('token', 'const'):
            if [token[1] for token in following[:6]] != ['=', 'Object', '.', 'freeze', '(', '[']:
                raise ManifestError('GAME_DATA_FILES must be a frozen array of literal URLs')
            map_literals = following[6:]
        if map_literals is not None:
            for item_kind, item in map_literals:
                if item == ']':
                    break
                if item_kind == 'string':
                    references.append(item)
                elif item != ',':
                    raise ManifestError('map assets must use literal URLs')
        if value == 'fetch' and len(following) > 1 and following[0][1] == '(' and following[1][0] == 'string':
            references.append(following[1][1])
        if value == 'new' and len(following) > 2 and following[0][1] == 'URL' and following[1][1] == '(' and following[2][0] == 'string':
            references.append(following[2][1])
    return references


class HtmlReferences(HTMLParser):
    def __init__(self):
        super().__init__()
        self.references = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'base':
            raise ManifestError('HTML base URLs are unsupported')
        for attribute in ('src', 'poster'):
            if attrs.get(attribute):
                self.references.append((attrs[attribute], True))
        if attrs.get('href') and tag in ('a', 'link'):
            self.references.append((attrs['href'], tag != 'a'))


def css_references(source):
    source = re.sub(r'/\*[\s\S]*?\*/', '', source)
    return [match.group(2).strip() for match in re.finditer(r'''url\(\s*(['"]?)(.*?)\1\s*\)''', source)] + re.findall(r'''@import\s+['"]([^'"]+)['"]''', source)


def resolve_reference(root, parent, reference, runtime=True):
    parsed = urlsplit(reference)
    if parsed.scheme or parsed.netloc:
        if runtime:
            raise ManifestError(f'external runtime URL: {reference}')
        return None  # credits may link to upstream attribution pages
    if not parsed.path:
        return None
    if parsed.path.startswith('/') or '\\' in parsed.path or parsed.query:
        raise ManifestError(f'unsupported asset URL: {reference}')
    target = (parent.parent / unquote(parsed.path)).resolve()
    if not target.is_relative_to(root):
        raise ManifestError(f'asset escapes repository: {reference}')
    if parsed.path.endswith('/') and target.is_dir():
        return None  # A literal URL base is not a downloadable file.
    if not target.is_file():
        raise ManifestError(f'missing asset: {reference} (from {parent.relative_to(root)})')
    return target


def build_manifest(root, game=GAME):
    root = Path(root).resolve()
    directory = (root / game).resolve()
    if not directory.is_relative_to(root):
        raise ManifestError('game directory escapes repository')
    worker = directory / 'service-worker.js'
    if not worker.is_file():
        raise ManifestError('missing service-worker.js version seed')
    excluded = {worker, directory / 'cache-manifest.js'}
    pending = [directory / 'index.html', directory / 'script.js', directory / 'credits.html']
    visited = set()
    while pending:
        path = pending.pop().resolve()
        if path in visited or path in excluded:
            continue
        if not path.is_relative_to(root) or not path.is_file():
            raise ManifestError(f'missing or out-of-repository closure file: {path.name}')
        visited.add(path)
        references = []
        if path.suffix in ('.js', '.mjs'):
            references = [(ref, True) for ref in js_references(path.read_text(encoding='utf-8'))]
        elif path.suffix in ('.html', '.css'):
            source = path.read_text(encoding='utf-8')
            references = [(ref, True) for ref in css_references(source)]
            if path.suffix == '.html':
                parser = HtmlReferences()
                parser.feed(source)
                references.extend(parser.references)
        for reference, runtime in references:
            target = resolve_reference(root, path, reference, runtime)
            if target is not None:
                pending.append(target)
    index = directory / 'index.html'
    normalized = {path: path.read_bytes() for path in visited}
    normalized[index] = stamp_build(normalized[index], INDEX_BUILD, ZERO_BUILD, 'index.html')
    worker_normalized = stamp_build(worker.read_bytes(), WORKER_BUILD, ZERO_BUILD, 'service-worker.js')

    def entries(contents):
        files = []
        for path, data in contents.items():
            url = quote(Path(os.path.relpath(path, directory)).as_posix(), safe='/.-_~')
            files.append({'url': url, 'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)})
        return sorted(files, key=lambda entry: entry['url'])

    build = seed_hash({'files': entries(normalized),
                       'workerSha256': hashlib.sha256(worker_normalized).hexdigest()})[:12]
    normalized[index] = stamp_build(normalized[index], INDEX_BUILD, build, 'index.html')
    worker_data = stamp_build(worker_normalized, WORKER_BUILD, build, 'service-worker.js')
    files = entries(normalized)
    worker_sha = hashlib.sha256(worker_data).hexdigest()
    version = seed_hash({'files': files, 'workerSha256': worker_sha})
    return {'build': build, 'version': version, 'workerSha256': worker_sha, 'files': files}


def check_build_stamps(root, manifest, game=GAME):
    directory = Path(root) / game
    for name, pattern in [('index.html', INDEX_BUILD), ('service-worker.js', WORKER_BUILD)]:
        data = (directory / name).read_bytes()
        if data != stamp_build(data, pattern, manifest['build'], name):
            return False
    return True


def write_build(root, manifest, game=GAME):
    directory = Path(root) / game
    # Validate both stamps before writing either file.
    stamped = [(directory / name, stamp_build((directory / name).read_bytes(), pattern, manifest['build'], name))
               for name, pattern in [('index.html', INDEX_BUILD), ('service-worker.js', WORKER_BUILD)]]
    for path, data in stamped:
        if path.read_bytes() != data:
            path.write_bytes(data)
    (directory / 'cache-manifest.js').write_text(render_manifest(manifest), encoding='utf-8')


def render_manifest(manifest):
    return HEADER + 'self.CAPITAL_CACHE_MANIFEST = ' + json.dumps(manifest, indent=2) + ';\n'


def check_manifest(path, manifest):
    return path.is_file() and path.read_text(encoding='utf-8') == render_manifest(manifest)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='stamp runtime build IDs and regenerate cache-manifest.js')
    mode.add_argument('--check', action='store_true', help='check generated bytes (default)')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        manifest = build_manifest(root)
        output = root / GAME / 'cache-manifest.js'
        if args.write:
            write_build(root, manifest)
        elif not check_build_stamps(root, manifest) or not check_manifest(output, manifest):
            raise ManifestError('manifest drift; run python3 -B scripts/build_capital_cache.py --write')
        print(f"Capital cache {'written' if args.write else 'OK'}: {len(manifest['files'])} files, "
              f"{sum(item['bytes'] for item in manifest['files'])} bytes, build {manifest['build']}, {manifest['version']}")
    except (ManifestError, OSError, UnicodeError) as error:
        print(f'Capital cache ERROR: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
