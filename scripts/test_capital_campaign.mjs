import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const src = await readFile(new URL('../Games/Capital Drive/campaign.js', import.meta.url), 'utf8');
const {createCampaign} = await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'));
const map = {spawn:{x:0,z:0},landmarks:[{id:'coals',name:'Coals',store:true,x:100,z:10},{id:'canberra-centre',x:200,z:-400}]};
const ctx = {pose:{x:0,z:0,speed:0},onFoot:false,vehicle:{stolen:false},vehicleHealth:100,wanted:0,respawnSerial:0,campaign:true,sandbox:false};
const campaign = createCampaign(map);
assert.equal(campaign.start({...ctx,sandbox:true}).ok,false);
assert.equal(campaign.start(ctx).ok,true);
assert.equal(campaign.start(ctx).ok,false);
campaign.update(10,{...ctx,sandbox:true}); assert.equal(campaign.state.active.elapsed,0);
for(let i=0;i<12;i++)campaign.update(.1,ctx);
assert.equal(campaign.state.active.stage,1);
for(let i=0;i<12;i++)campaign.update(.1,{...ctx,pose:{x:100,z:10,speed:12}});
assert.equal(campaign.state.completed.length,0,'moving through drop cannot complete');
for(let i=0;i<12;i++)campaign.update(.1,{...ctx,pose:{x:100,z:10,speed:0}});
assert.deepEqual(campaign.state.completed,['late-parcel']);
const completion=campaign.drainEvents().filter(e=>e.type==='complete');assert.equal(completion.length,1);
campaign.update(1,ctx);assert.equal(campaign.drainEvents().length,0,'reward fires once');
const restored=createCampaign(map,campaign.serialize());assert.equal(restored.current().id,'under-the-awning');
restored.start(ctx);for(let i=0;i<30;i++)restored.update(.1,{...ctx,onFoot:true,pose:{x:100,z:10}});
assert.equal(restored.state.active.stage,0,'outside store cannot collect indoor ledger');
for(let i=0;i<25;i++)restored.update(.1,{...ctx,onFoot:true,interior:{storeId:'coals',atCounter:true}});
assert.equal(restored.state.active.stage,1);
restored.update(.1,{...ctx,respawnSerial:1});assert.equal(restored.state.active,null);assert.equal(restored.state.failed,true);
assert.deepEqual(restored.serialize().completed,['late-parcel']);assert.equal(restored.start(ctx).ok,true);
assert.throws(()=>createCampaign(map,{version:1,completed:['borrowed-wheels']}));
assert.throws(()=>createCampaign(map,{version:1,completed:['late-parcel','late-parcel']}));
assert.throws(()=>createCampaign(map,{version:1,completed:[],money:100}));
assert.throws(()=>restored.update(NaN,ctx));
assert.ok(Object.isFrozen(campaign.snapshot()));
console.log('PASS campaign: ordered saved chapters; normal stop/indoor gates; sandbox blocked; one reward; recovery retry; corrupt saves rejected');
