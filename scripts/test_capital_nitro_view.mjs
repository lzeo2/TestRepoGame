import assert from 'node:assert/strict';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
import { BY_ID } from '../assets/car-arcade/fleet.js';
import { createNitroView } from '../Games/Capital Drive/nitro-view.js';

const scene = new THREE.Scene();
const view = createNitroView(scene);
const [exhaust] = scene.children;
const car = new THREE.Object3D();
car.position.set(21, 3, -17);
car.rotation.set(.1, .7, 0);
assert.equal(exhaust.visible, false);
view.update(car, BY_ID.lantern, true, 1/60);
assert(exhaust.visible);
assert.equal(exhaust.count, 2);
assert(exhaust.position.equals(car.position));
assert(exhaust.quaternion.equals(car.quaternion));
const transform = new THREE.Matrix4();
const origin = new THREE.Vector3();
exhaust.getMatrixAt(0, transform);
origin.setFromMatrixPosition(transform);
assert(origin.x < 0 && origin.z > 1, 'plumes attach to the rear bumper');
const before = transform.clone();
view.update(car, BY_ID.lantern, true, 1/60);
exhaust.getMatrixAt(0, transform);
assert(!before.equals(transform), 'active thrust animates existing instances');
const version = exhaust.instanceMatrix.version;
view.update(car, BY_ID.lantern, false);
assert.equal(exhaust.visible, false);
assert.equal(exhaust.instanceMatrix.version, version);
view.dispose();
view.dispose();
assert.equal(scene.children.length, 0);
console.log('PASS nitro exhaust: two animated rear flames in one reusable batch, no idle update, disposal');
