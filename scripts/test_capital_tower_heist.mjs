import assert from 'node:assert/strict';
import {createInteriors} from '../Games/Capital Drive/interiors.js';
import {createInteriorPeople} from '../Games/Capital Drive/interior-people.js';
import {createHeistActivities} from '../Games/Capital Drive/heist-activities.js';

// Authored fictional archive geometry; this is not a real tower room or security plan.
const site={id:'black-mountain-archive',kind:'tower',name:'Black Mountain Tower archive',x:100,z:200,yaw:0,width:10.4,depth:7.6,floor:12,point:(across,forward)=>({x:100-across,z:200-forward})};
const interiors=createInteriors({buildings:[]},{heightAt:()=>12,heistSites:[site]});
const entry=interiors.entries[0],actor={...site.point(0,-2.05),yaw:0};
const roomPlan=interiors.enter(entry,actor),people=createInteriorPeople();people.load(roomPlan);
assert.equal(roomPlan.rooms[0].kind,'tower-archive');
assert(roomPlan.furniture.some(item=>item.kind==='ledger-case'));
assert(!roomPlan.furniture.some(item=>['cash-safe','jewellery-case','jewel-safe'].includes(item.kind)));
const employee=people.getCrimeTarget(roomPlan.heist.employee.id);
const room={id:roomPlan.id,storeId:site.id,heistSiteId:site.id,employeeId:employee.id,loot:roomPlan.heist.loot};
const pose=roomPlan.counter,dx=employee.x-pose.x,dz=employee.z-pose.z;
const context={pose,onFoot:true,wanted:0,indoors:true,room,employee,armed:true,aiming:true,aimYaw:Math.atan2(-dx,-dz)};
const pickup={...context,pose:room.loot,armed:false,aiming:false};
const outdoors=(distance,wanted=0)=>({pose:{x:site.x+distance,z:site.z},onFoot:true,wanted});
const heat=[],rewards=[];
const heists=createHeistActivities({sites:[site],canSee:interiors.hasLineOfSight,onHeat:event=>heat.push(event),onReward:event=>rewards.push(event)});
assert.equal(heists.interact(outdoors(0)),null,'exterior interaction belongs to the real door');
assert.equal(heists.interact({...context,onFoot:false}),null);
assert.equal(heists.interact({...context,room:{...room,heistSiteId:'civic-bank'}}),null);
assert.equal(heists.interact({...context,employee:{...employee,kind:'visitor'}}),null);
assert.equal(heists.interact({...context,employee:{...employee,health:0}}),null);
assert.equal(heists.interact({...context,armed:false}).ok,false,'case cannot skip employee confrontation');
assert.equal(heists.interact({...context,wanted:2}).ok,false);
assert.deepEqual(heat,[]);assert.deepEqual(rewards,[]);
assert(heists.interact(context).ok);
assert.equal(heists.snapshot().phase,'surrender');
assert.equal(heists.snapshot().indoorTarget.name,'Archive case');
assert.match(heists.snapshot().guidance,/archive case/);
assert.equal(heists.interact(context),null,'employee interaction cannot remotely collect case');
assert(heists.interact(pickup).ok);
assert.equal(heists.snapshot().phase,'escape');
assert.deepEqual(heat,[{id:site.id,kind:'tower',point:{x:site.x,z:site.z},severity:2}]);
assert.equal(heists.interact(pickup),null);assert.equal(heat.length,1,'one collection emits heat once');
heists.step(.1,outdoors(80));assert.equal(rewards.length,0,'search must actually begin');
heists.step(.1,{...pickup,wanted:2});
heists.step(.1,pickup);assert.equal(rewards.length,0,'inside the room cannot finish escape');
heists.step(.1,outdoors(20));assert.equal(rewards.length,0,'clear heat alone does not satisfy escape distance');
heists.step(.1,outdoors(80,1));assert.equal(rewards.length,0,'distant pickup still requires clear stars');
assert(heists.step(.1,outdoors(48)).ok);
assert.deepEqual(rewards,[{id:site.id,kind:'tower',amount:2200}]);
assert.equal(heists.active,false);
assert.equal(heists.interact(context).ok,false,'duplicate attempt is blocked during cooldown');
assert.match(heists.interact(context).message,/available in 360s/);
for(let i=0;i<359;i++)heists.step(1,outdoors(80));
assert.equal(heists.interact(context).ok,false,'cooldown cannot finish early');
assert.equal(rewards.length,1);
heists.step(1,outdoors(80));
assert(heists.interact(context).ok,'archive can be replayed after the existing 360-second policy');
assert(heists.interact(pickup).ok);
heists.step(.1,outdoors(80,2));
assert(heists.step(.1,outdoors(80)).ok);
assert.equal(rewards.length,2,'a fresh completed attempt receives exactly one payout');
assert.equal(heat.length,2);
assert.equal(heists.step(.1,outdoors(80)),null);
assert.equal(rewards.length,2);
// Practice uses the same physical confrontation and collection without career effects.
assert(heists.interact({...context,sandbox:true}).ok);
assert(heists.interact({...pickup,sandbox:true}).ok);
assert(heists.step(.1,{...outdoors(80),sandbox:true}).ok);
assert.equal(heat.length,2);assert.equal(rewards.length,2);
const retry=createHeistActivities({sites:[site],canSee:interiors.hasLineOfSight});
assert(retry.interact(context).ok);assert.equal(retry.step(.1,{...context,recovering:true}).ok,false);
assert(retry.interact(context).ok,'interrupted confrontation does not mark archive completed');
assert(retry.cancel());
assert(retry.interact({...context,armed:false,aiming:false,employee:{...employee,lastPlayerHit:true},wanted:1}).ok,'existing on-foot recent-hit confrontation is preserved');
assert.equal(createInteriors({buildings:[]},{heistSites:[{...site,depth:6}]}).entries.length,0,'undersized archive descriptor is rejected');
people.clear();interiors.leave(actor);
console.log('PASS fictional tower archive: actual room/employee/case, confrontation guards, one heat event, indoor/search/distance escape gates, once-per-attempt payout, cooldown replay, practice and recovery isolation.');
