function policeFixture({vehicles=[car],altitude=0,allies=[],targetY,playerHealth=100}={}) {
  const officer={id:'officer',x:0,z:0,yaw:0,mode:'foot',health:100,fireCooldown:0,interiorId:null,car:{id:'patrol',x:50,z:50,yaw:0,active:true}};
  const disabled=[1,2,3].map(id=>({id:`disabled:${id}`,x:50,z:50,health:0,mode:'foot'}));
  const state={police:[officer,...disabled],wanted:3,health:playerHealth,mode:'foot',weapon:'unarmed',heat:100};
  const target={x:0,z:-20,speed:0,...(targetY===undefined?{}:{y:targetY})};
  const simulation={player:{x:50,z:50},graph:{edges:[],nodes:new Map()},hasLineOfSight:()=>true,canOccupy:()=>false,moveActor:()=>({blocked:true})};
  let queries=0,last;
  const ai=createPolice(simulation,{heightAt:()=>0,playerAltitude:()=>altitude,getAllies:()=>allies,shotClear:(from,to,ctx)=>{
    queries++;last={from,to,ctx};const length=Math.hypot(to.x-from.x,to.y-from.y,to.z-from.z);
    const shot={x:from.x,y:from.y,z:from.z,dx:(to.x-from.x)/length,dy:(to.y-from.y)/length,dz:(to.z-from.z)/length,range:length,interiorId:ctx.interiorId};
    return cover.trace(shot,null,vehicles)>=length-.01;
  }});
  return {ai,state,target,officer,queries:()=>queries,last:()=>last};
}
