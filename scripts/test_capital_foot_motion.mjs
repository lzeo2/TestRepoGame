import assert from 'node:assert/strict';
import {createFootMotion} from '../Games/Capital Drive/foot-motion.js';
import {footCameraFrame} from '../Games/Capital Drive/camera-control.js';

const close=(a,b)=>assert(Math.abs(a-b)<1e-10,`${a} != ${b}`);
const motion=createFootMotion(),room={};
const actor={x:4,z:8,yaw:Math.PI-.06,speed:0,jumpHeight:0,impactSerial:3};
assert.equal(motion.sample(actor,room,.5),actor,'first frame uses the live actor');
motion.capture(actor,room);
Object.assign(actor,{x:4.2,z:7.8,yaw:-Math.PI+.06,speed:6,jumpHeight:.2});
const expected={...actor};
const midpoint=motion.sample(actor,room,.5);
assert.notEqual(midpoint,actor);
close(midpoint.x,4.1);close(midpoint.z,7.9);close(midpoint.yaw,Math.PI);
close(midpoint.jumpHeight,.1);close(midpoint.speed,3);
assert.equal(midpoint.impactSerial,3,'discrete actor state remains current');
assert.deepEqual(actor,expected,'render interpolation leaves the live actor intact');
const camera=footCameraFrame(midpoint),liveCamera=footCameraFrame(actor);
close(camera.camera.x,liveCamera.camera.x-.1);
close(camera.target.y,liveCamera.target.y-.1);
assert.equal(motion.sample(actor,room,0),midpoint,'pause does not rewind the display pose');
close(midpoint.x,4.1);
assert.equal(motion.sample(actor,room,1),actor,'clamps to the current tick');
motion.capture(actor,room);
actor.x+=.06;
assert.equal(motion.sample(actor,room,.25),midpoint,'reuses the render pose on the next tick');
close(midpoint.x,4.215);
assert.equal(motion.sample(actor,{},.5),actor,'room transitions cut');
assert.equal(motion.sample(actor,room,.5),actor,'old room history was discarded');
motion.capture(actor,room);
actor.z+=3;
assert.equal(motion.sample(actor,room,.5),actor,'teleports cut within the same room');
motion.capture(actor,room);
actor.x+=.06;
assert.equal(motion.sample(actor,room,.5,true),actor,'explicit camera cuts bypass history');
motion.capture(actor,room);
assert.equal(motion.sample(null,room,.5),null,'combat, ragdolls and vehicle modes discard history');
assert.equal(motion.sample(actor,room,.5),actor,'returning to locomotion starts fresh');
console.log('PASS fixed-step foot render motion, shared camera pose, pause and discontinuities');

const elevated={x:1,z:2,yaw:0,speed:1,jumpHeight:0,feetY:5,impactSerial:9};
motion.capture(elevated,room);elevated.feetY=5.2;
const raised=motion.sample(elevated,room,.5);close(raised.feetY,5.1);
assert.equal(elevated.feetY,5.2,'camera/mesh floor interpolation never changes source feet');
const raisedCamera=footCameraFrame(raised),floorCamera=footCameraFrame(elevated);
close(raisedCamera.camera.y,floorCamera.camera.y-.1);
assert.equal(motion.sample(elevated,room,NaN),raised,'invalid render fraction keeps the last finite presentation');
assert(Number.isFinite(raised.x)&&Number.isFinite(raised.feetY));
motion.capture(elevated,room);elevated.x+=.1;elevated.impactSerial++;
assert.equal(motion.sample(elevated,room,.5),elevated,'a fresh impact bypasses ordinary motion history');
motion.capture(elevated,room);elevated.impactTime=.2;
assert.equal(motion.sample(elevated,room,.5),elevated,'active impact cannot be interpolated as walking');
console.log('PASS finite bounded floor/camera interpolation, current impact bypass and unchanged source pose');

elevated.impactTime=0;motion.capture(elevated,room);delete elevated.feetY;elevated.x+=.1;
assert(!Object.hasOwn(motion.sample(elevated,room,.5),'feetY'),'reused render pose cannot retain a removed floor override');
