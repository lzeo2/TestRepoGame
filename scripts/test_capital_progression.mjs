import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createProgression } from '../Games/Capital Drive/progression.js';
const map = JSON.parse(await fs.readFile(new URL('../Games/Capital Drive/data/canberra.json', import.meta.url), 'utf8'));
const ctx = (pose = map.spawn, extra = {}) => ({ pose: { ...pose }, onFoot: false, vehicle: { modelId: 'lantern', color: '#e7e6df', stolen: false }, vehicleHealth: 100, wanted: 0, respawnSerial: 0, ...extra });
const p = createProgression(map);
assert.equal(p.state.cash, 1000);
assert.equal(p.startJob('priority-parcel', ctx()).ok, false);
assert.equal(p.startJob('crescent-parcel', ctx()).ok, true);
assert.equal(p.state.cash, 1000, 'clicking a job cannot pay');
p.update(0, ctx()); assert.equal(p.state.activeJob.stage, 0, 'pause freezes stages');
p.update(1, ctx()); assert.equal(p.state.activeJob.stage, 1);
p.update(1, ctx(map.spawn, { onFoot: true })); assert.equal(p.state.cash, 1000);
p.update(1, ctx(p.state.activeJob.target)); assert.equal(p.state.cash, 1300);
assert.deepEqual(p.state.completedJobs, ['crescent-parcel']);
p.update(1, ctx(p.jobs[0].stages[1])); assert.equal(p.state.cash, 1300, 'completed instance cannot pay again');
assert.equal(p.startJob('crescent-circuit', ctx()).ok, true);
const race = p.jobs.find(job => job.type === 'race');
p.update(1, ctx(race.stages[2])); assert.equal(p.state.activeJob.stage, 0, 'checkpoints are ordered');
for (const target of race.stages) p.update(1, ctx(target));
assert.equal(p.state.cash, 1850);
assert.equal(p.startJob('wagon-recovery', ctx()).ok, true);
p.update(1, ctx(p.garage)); assert.equal(p.state.activeJob.stage, 0, 'owned wrong vehicle cannot satisfy theft');
p.update(1, ctx(p.garage, { vehicle: { modelId: 'orchard', stolen: false } })); assert.equal(p.state.activeJob.stage, 0);
const stolen = { vehicle: { modelId: 'orchard', stolen: true } };
p.update(1, ctx(p.garage, stolen)); assert.equal(p.state.activeJob.stage, 0, 'theft requires its actual pickup marker');
p.update(1, ctx(p.state.activeJob.target, stolen)); assert.equal(p.state.activeJob.stage, 1);
p.update(1, ctx(p.garage, { ...stolen, wanted: 1 })); assert.ok(p.state.activeJob);
p.update(1, ctx(p.garage, stolen)); assert.equal(p.state.cash, 2600);
assert.equal(p.startJob('clear-the-search', ctx()).ok, true);
const getaway = p.jobs.find(job => job.type === 'getaway');
p.update(10, ctx(getaway.stages[0])); assert.equal(p.state.activeJob.stage, 0, 'must encounter wanted');
p.update(1, ctx(getaway.stages[0], { wanted: 2 })); assert.equal(p.state.activeJob.stage, 1);
p.update(7, ctx(getaway.stages[1])); assert.ok(p.state.activeJob);
p.update(1, ctx(getaway.stages[1], { wanted: 1 }));
p.update(7, ctx(getaway.stages[1])); assert.ok(p.state.activeJob, 'fresh wanted resets clear timer');
p.update(1, ctx(getaway.stages[1])); assert.equal(p.state.cash, 3250);
p.startJob('priority-parcel', ctx());
p.update(111, ctx(p.jobs.at(-1).stages[0])); assert.equal(p.state.activeJob, null);
assert.equal(p.state.completedJobs.includes('priority-parcel'), false);
p.startJob('priority-parcel', ctx()); p.penalize('Arrested');
assert.equal(p.state.completedJobs.length, 4); assert.equal(p.state.activeJob, null);
p.startJob('priority-parcel', ctx()); p.update(1, ctx(map.spawn, { respawnSerial: 1 }));
assert.equal(p.state.activeJob, null, 'respawn aborts without completing');
assert.equal(p.buyVehicle('orchard').ok, false, 'remote garage blocked');
p.update(0, ctx(p.garage));
assert.equal(p.buyVehicle('orchard').ok, true);
assert.equal(p.buyVehicle('orchard').ok, false);
assert.equal(p.paintVehicle('orchard', 'red').ok, false);
assert.equal(p.paintVehicle('orchard', '#abcdef').ok, true);
p.update(0, ctx(p.garage, { vehicleHealth: 45 }));
assert.equal(p.repairVehicle().vehicleHealth, 100);
assert.equal(p.repairVehicle().ok, false, 'repeat repair cannot charge twice');
assert.equal(p.storeVehicle({ modelId: 'relay' }).ok, false);
assert.equal(p.storeVehicle({ modelId: 'lantern', color: '#123456' }).ok, true);
const saved = p.serialize();
const loaded = createProgression(map, saved);
assert.deepEqual(loaded.serialize(), saved);
saved.ownedVehicles[0].color = '#000000';
assert.notEqual(loaded.state.ownedVehicles[0].color, saved.ownedVehicles[0].color, 'load detached from source');
for (const bad of [{}, { ...loaded.serialize(), version: 2 }, { ...loaded.serialize(), cash: -1 }, { ...loaded.serialize(), cash: Infinity }, { ...loaded.serialize(), completedJobs: ['unknown'] }, { ...loaded.serialize(), completedJobs: ['priority-parcel'] }, { ...loaded.serialize(), ownedVehicles: [] }, { ...loaded.serialize(), unknown: true }]) assert.throws(() => createProgression(map, bad));
assert.throws(() => p.update(NaN, ctx()));
const events = p.drainEvents(); assert.ok(events.some(event => event.type === 'job-complete')); assert.equal(p.drainEvents().length, 0);
assert.equal(loaded.startJob('crescent-parcel', ctx()).ok, true, 'new mission instance permits recurring delivery');
const repeat = createProgression(map);
const firstJob = repeat.jobs[0], pickup = firstJob.stages[0], drop = firstJob.stages[1];
repeat.startJob(firstJob.id, ctx(pickup)); repeat.update(1, ctx(pickup)); repeat.update(1, ctx(drop));
assert.equal(repeat.state.cash, 1300);
assert.equal(repeat.startJob(firstJob.id, ctx(drop)).ok, true);
assert.equal(repeat.startJob(firstJob.id, ctx(drop)).ok, false, 'extra click cannot replace the active instance');
repeat.update(3, ctx(drop)); assert.equal(repeat.state.activeJob.stage, 0, 'repeat requires a fresh pickup');
assert.equal(repeat.state.cash, 1300);
repeat.update(1, ctx(pickup)); assert.equal(repeat.state.activeJob.stage, 1);
repeat.update(1, ctx(pickup)); assert.equal(repeat.state.cash, 1300, 'repeat requires fresh drop arrival');
repeat.update(1, ctx(drop)); assert.equal(repeat.state.cash, 1600);
repeat.update(20, ctx(drop)); assert.equal(repeat.state.cash, 1600, 'repeat pays exactly once');
assert.deepEqual(repeat.state.completedJobs, ['crescent-parcel'], 'unlock IDs remain unique');
repeat.update(0, ctx(repeat.garage, { vehicleHealth: 23 }));
assert.equal(repeat.buyVehicle('orchard').ok, true);
assert.equal(repeat.state.ownedVehicles.find(car => car.id === 'lantern').health, 23, 'purchase preserves outgoing car damage');
assert.equal(p.retrieveVehicle('lantern').ok, true);
p.update(0, ctx(map.spawn)); assert.equal(p.retrieveVehicle('lantern').ok, false, 'remote retrieval blocked');
p.update(0, ctx(p.garage, { wanted: 1 })); assert.equal(p.retrieveVehicle('lantern').ok, false, 'wanted retrieval blocked');
p.update(0, ctx(p.garage, { vehicleHealth: 32, vehicle: { modelId: 'lantern', color: 0x123456, stolen: false } }));
assert.equal(p.retrieveVehicle('unknown').ok, false);
const retrieved = p.retrieveVehicle('lantern');
assert.equal(retrieved.vehicle.health, 32, 'retrieving live car cannot repair for free');
assert.equal(retrieved.vehicle.color, '#123456'); assert.equal(retrieved.vehicle.stored, false);
assert.equal(p.retrieveVehicle('orchard').ok, true);
p.update(0, ctx(p.garage, { vehicle: { modelId: 'orchard', color: '#abcdef', stolen: false } }));
assert.equal(p.retrieveVehicle('lantern').vehicle.health, 32, 'switching away/back cannot repair for free');
console.log('Capital progression: mission order, arrival, time, theft, escape, garage and save checks passed.');
