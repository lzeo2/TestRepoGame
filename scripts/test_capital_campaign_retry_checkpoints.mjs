import assert from 'node:assert/strict';
import {createCampaign} from '../Games/Capital Drive/campaign.js';
import {createStealthContracts} from '../Games/Capital Drive/stealth-contracts.js';
const districts=['manuka','foreshore','canberra-centre','redhill','kingston','griffith'].map((id,i)=>({id,x:i*470,z:0}));
const map={spawn:{x:0,z:0},landmarks:[{id:'coals',store:true,name:'Coals',x:20,z:10},...districts],roads:districts.flatMap(({id,x,z})=>[-60,0,60].map((offset,i)=>({id:`${id}:${i}`,name:'Test Street',points:[[x-120,z+offset],[x+120,z+offset]],width:8,type:'residential'})))};
const ctx={pose:map.spawn,onFoot:true,wanted:0,respawnSerial:0,campaign:true,health:100,vehicleHealth:100};
const tick=(campaign,change={},n=8)=>{for(let i=0;i<n;i++)campaign.update(.1,{...ctx,...change});};
const fail=(campaign,serial=1)=>campaign.update(.1,{...ctx,respawnSerial:serial,recovering:true});
const main=createCampaign(map,{version:1,completed:[]});
assert.equal(main.captureRetry(),null);
assert(main.start(ctx).ok);main.drainEvents();
const original=structuredClone(main.state.active),progress=main.serialize();
const replaced=main.captureRetry(),zero=main.captureRetry();
assert(Object.isFrozen(zero));assert.deepEqual(Object.keys(zero),['id','stage']);
assert.throws(()=>{zero.stage=99;},TypeError);
tick(main,{onFoot:false,vehicle:{stolen:true}});assert.equal(main.state.active.stage,1);
const future=main.captureRetry();fail(main);
assert.deepEqual(main.drainEvents().at(-1),{type:'failed',id:zero.id,stage:1,message:'Mission failed.'});
for(const token of [null,{}, {...zero},replaced])assert.equal(main.resumeRetry(token,{...ctx,respawnSerial:1}).ok,false);
for(const change of [{recovering:true},{sandbox:true},{campaign:false},{respawnSerial:0},{pose:{x:NaN,z:0}}])assert.equal(main.resumeRetry(zero,{...ctx,respawnSerial:1,...change}).ok,false);
assert(main.resumeRetry(zero,{...ctx,respawnSerial:1,wanted:3,onFoot:false}).ok,'retry permits incident heat and vehicle mode');
assert.equal(main.state.active.stage,0);assert.deepEqual(main.state.active.target,original.target);
assert.equal(main.state.active.remaining,original.remaining);assert.equal(main.state.active.serial,1);
assert.equal(main.state.active.sawWanted,original.sawWanted,'copied launch incident state is retained');
assert.deepEqual(main.drainEvents().filter(e=>e.type==='started'),[],'retry does not replay launch effects');
assert.deepEqual(main.serialize(),progress);
fail(main,2);assert.equal(main.resumeRetry(future,{...ctx,respawnSerial:2}).ok,false,'future checkpoints retired after rewind');
assert(main.resumeRetry(zero,{...ctx,respawnSerial:2}).ok,'same checkpoint survives repeated failure in same attempt');
assert.equal(main.resumeRetry(zero,{...ctx,respawnSerial:2}).ok,false,'cannot retry a live attempt');
tick(main,{respawnSerial:2,onFoot:false,vehicle:{stolen:true}});
tick(main,{respawnSerial:2,onFoot:false,vehicle:{stolen:true},pose:{...main.state.active.target,speed:0}},12);
assert.equal(main.state.active,null);assert(main.isCompleted(zero.id));
assert.equal(main.resumeRetry(zero,{...ctx,respawnSerial:2}).ok,false,'completion retires checkpoints');
assert.equal(main.drainEvents().filter(e=>e.type==='complete').length,1);

