import assert from 'node:assert/strict';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
import { createVehicleOccupantsView } from '../Games/Capital Drive/vehicle-occupants-view.js';
import { createRideServiceView } from '../Games/Capital Drive/ride-service-view.js';
import { createBusView } from '../Games/Capital Drive/bus-view.js';
const road={id:'lower-road'},calls=[];
let legacyCalls=0;
const heightAt=()=>{legacyCalls++;return 30;};
const vehicleHeightAt=(pose,actualRoad)=>{calls.push({...pose,road:actualRoad});return 2+pose.z*.1;};
const car={id:'car',modelId:'lantern',active:true,occupied:true,x:0,z:0,yaw:0,edge:{road}};
const options={vehicleHeightAt},matrix=new THREE.Matrix4();
const scene=new THREE.Scene(),occupants=createVehicleOccupantsView(scene,heightAt,options);
const original={...car};occupants.update(.016,{cars:[car],focus:car});
assert.equal(legacyCalls,0,'seated occupants do not sample global bridge deck');
assert.equal(calls.length,3);assert(calls.every(sample=>sample.road===road&&sample.yaw===car.yaw));
const head=scene.children[0].getObjectByName('Vehicle occupant head');head.getMatrixAt(0,matrix);
assert(matrix.elements[13]<5,'seated body follows lower car surface');
occupants.addExit({id:'exit',x:0,z:0});occupants.update(.016,{cars:[],focus:car});assert(legacyCalls>0,'standing exits retain ordinary ground');
const rideScene=new THREE.Scene(),ride=createRideServiceView(rideScene,heightAt,options);
ride.update({car,passenger:true,driver:{id:'driver',x:1,z:1,yaw:0,active:true}},{focus:car});
const mesh=rideScene.getObjectByName('Yoober Lantern');assert.equal(mesh.position.y,2.18);
assert(Math.abs(mesh.rotation.x-Math.atan2(-.4,4))<1e-10,'ride chassis samples actual front and rear');
const seated=rideScene.getObjectByName('Seated ride passengers');seated.getMatrixAt(0,matrix);assert(matrix.elements[13]<5);
const driver=rideScene.getObjectByName('Cancelled Yoober driver');driver.getMatrixAt(0,matrix);assert(matrix.elements[13]>30,'exited ride driver stays on pedestrian ground');
const busScene=new THREE.Scene(),busView=createBusView(busScene,heightAt,options);
const bus={...car,id:'bus',playerAboard:true};busView.update([bus],car);
const group=busScene.children[0].children.find(child=>child.isGroup);assert(group);assert.equal(group.position.y,2.03);
assert(Math.abs(group.rotation.x-Math.atan2(-.8,8))<1e-10);
const passenger=busScene.getObjectByName('Seated bus player passenger');
assert(passenger,'actual bus passenger batch exists');passenger.getMatrixAt(0,matrix);
const expected=new THREE.Matrix4().compose(group.position,group.quaternion,new THREE.Vector3(1,1,1));
assert(matrix.elements.every((value,i)=>Math.abs(value-expected.elements[i])<1e-6),'bus passenger shares pitched chassis transform');
assert.deepEqual(car,original,'view does not mutate physical car');
assert(calls.every(sample=>sample.road===road&&sample.yaw===car.yaw),'all support samples preserve road and heading');
occupants.dispose();ride.dispose();busView.dispose();
const legacyScene=new THREE.Scene(),legacyRide=createRideServiceView(legacyScene,heightAt),legacyBus=createBusView(legacyScene,heightAt),legacyOccupants=createVehicleOccupantsView(legacyScene,heightAt);
legacyRide.update({car},{focus:car});assert.equal(legacyScene.getObjectByName('Yoober Lantern').position.y,30.18);
legacyBus.update([bus],car);
assert.equal(legacyBus.stats.buses,1);legacyOccupants.update(.01,{cars:[car],focus:car});assert.equal(legacyOccupants.stats.drivers,1);
legacyRide.dispose();legacyBus.dispose();legacyOccupants.dispose();
console.log('PASS vehicle support views: lower-road chassis/seated transforms, road/heading samples, bus pitch, legacy exit grounding and unchanged owner poses');
