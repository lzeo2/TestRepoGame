import assert from 'node:assert/strict';
import {createCampaignScenes} from '../Games/Capital Drive/campaign-scenes.js';
import {createSimulation} from '../Games/Capital Drive/simulation.js';
const map={bounds:{minX:-100,maxX:100,minZ:-100,maxZ:100},buildings:[],roads:[],landmarks:[],spawn:{x:0,z:0,yaw:0}};
const context={mode:'street',character:'student',pose:{x:0,z:0,yaw:0},health:100,playerMode:'foot',hostiles:[],hiredMembers:[{id:'merc-river'},{id:'merc-stone'}],rehireSerial:{'merc-river':4,'merc-stone':2}};
const scene=()=>createCampaignScenes(map,createSimulation(map,{trafficCount:0}));
const crew=scene(),ctx={...context,hiredHealth:{'merc-river':0,'merc-stone':33}},input=structuredClone(ctx);
crew.update(ctx,.1);assert.deepEqual(ctx,input,'construction never mutates persisted inputs');
assert.equal(crew.people.find(p=>p.id==='merc-river').health,0);
assert.equal(crew.people.find(p=>p.id==='merc-river').mode,'down');
assert.equal(crew.people.find(p=>p.id==='merc-river').armed,false);
assert.equal(crew.people.find(p=>p.id==='merc-stone').health,33);
for(let i=0;i<10;i++)crew.update({...ctx,hiredHealth:{'merc-river':100,'merc-stone':100}},.1);
assert.deepEqual(crew.people.map(p=>p.health),[0,33],'supplied health is initial admission only; live history remains authoritative');
crew.clear();crew.update(ctx,.1);assert.deepEqual(crew.people.map(p=>p.health),[0,33],'clear cannot revive or heal history');
const paid={...ctx,rehireSerial:{...ctx.rehireSerial,'merc-river':5}};
crew.update(paid,.1);assert.equal(crew.people.find(p=>p.id==='merc-river').health,100,'strictly higher paid token renews a dead body once');
const victim=crew.people.find(p=>p.id==='merc-river');
assert(crew.receiveHit({kind:'shot',targetId:victim.id,from:{x:victim.x+1,z:victim.z},to:victim,damage:17}));
crew.update(paid,.1);assert.equal(crew.people.find(p=>p.id===victim.id).health,83,'holding paid token never repeatedly heals');
const reloaded=scene();reloaded.update({...paid,hiredHealth:()=>0},.1);
assert(reloaded.people.every(p=>p.health===0),'new scene restores supplied death even with nonzero historical purchase tokens');
const legacy=scene();legacy.update(context,.1);assert(legacy.people.every(p=>p.health===100),'legacy unspecified health defaults to 100');

const combat=scene();combat.update({...context,hiredMembers:[{id:'merc-river'}]},.1);
const ally=combat.people[0];
const disabled=Array.from({length:4},(_,i)=>({id:`police:dead-${i}`,x:ally.x+3,z:ally.z,health:0,mode:'foot'}));
const fifth={id:'police:fifth',x:ally.x+8,z:ally.z,health:100,mode:'foot'};
const sixth={id:'police:sixth',x:ally.x+5,z:ally.z,health:100,mode:'foot'};
const firing={...context,hiredMembers:[{id:'merc-river'}],hostiles:[...disabled,fifth,sixth]};
for(let i=0;i<15;i++)combat.update(firing,.1);
assert(combat.drainEvents().some(event=>event.type==='ally-shot'&&event.targetId===sixth.id),'dead first four cannot hide the fifth/sixth eligible ground threat');
const otherRoom=Array.from({length:6},(_,i)=>({...fifth,id:`police:other-${i}`,interiorId:'other'}));
for(let i=0;i<15;i++)combat.update({...firing,hostiles:[...otherRoom,fifth]},.1);
assert(combat.drainEvents().some(event=>event.type==='ally-shot'&&event.targetId===fifth.id),'room eligibility is checked before the six-threat cap');
for(const item of [crew,reloaded,legacy,combat])item.dispose();
console.log('Capital hired health PASS: reload preserves zero/wounded HP, legacy defaults, authoritative live history, one paid renewal, supplied callback health and six-threat eligibility before capping.');
