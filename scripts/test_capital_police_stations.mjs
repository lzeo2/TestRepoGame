import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from '../assets/car-arcade/vendor/three.module.js';
import {applyMapExpansion} from '../Games/Capital Drive/map-expansion.js';
import {applyAirport} from '../Games/Capital Drive/airport.js';
import {applyRoadProfiles} from '../Games/Capital Drive/road-network.js';
import {applyStreetAssetRoofs} from '../Games/Capital Drive/street-assets.js';
import {createSimulation} from '../Games/Capital Drive/simulation.js';
import {createTerrainSampler} from '../Games/Capital Drive/terrain.js';
import {createShotObstacles} from '../Games/Capital Drive/shot-obstacles.js';
import {createPoliceStations} from '../Games/Capital Drive/police-stations.js';
import {createPoliceStationView} from '../Games/Capital Drive/police-station-view.js';

const data=async n=>JSON.parse(await readFile(new URL(`../Games/Capital Drive/data/${n}.json`,import.meta.url)));
const [south,north,profiles,airport,airportTerrain]=await Promise.all(['canberra','canberra-north','road-profiles','airport','airport-terrain'].map(data));
const map=applyAirport(applyStreetAssetRoofs(applyMapExpansion(applyRoadProfiles(south,profiles),north)),airport,airportTerrain);
const terrain=createTerrainSampler(map), simulation=createSimulation(map,{trafficCount:0,parkedCount:0,isOnBridge:terrain.isOnBridge});
const start=performance.now(),state=createPoliceStations(map,simulation,terrain.heightAt);
const placementMilliseconds=Math.round(performance.now()-start);
assert.equal(state.sites.length,3);
assert.equal(state.responseLoss(),0);
assert.equal(state.patrolStations().length,3);
for(const site of state.sites){
  assert(site.place.description.startsWith('Fictional police post'));
  assert(simulation.canOccupy({...site, yaw:site.approach.yaw},{length:2,width:1}));
  assert(simulation.canOccupy(site.approach,{length:1,width:1}));
}
map.barriers=[...(map.barriers||[]),...state.barriers];
simulation.registerStaticBarriers(state.barriers);
const shots=createShotObstacles(map,{heightAt:terrain.heightAt});
const site=state.sites[0],body={x:site.x,z:site.z,yaw:site.approach.yaw};
assert(!simulation.canOccupy(body,{length:2,width:1}));
assert(simulation.canOccupy(site.approach,{length:1,width:1}));
const scene=new THREE.Scene(),view=createPoliceStationView(scene,state);
view.update(site.approach);
assert.equal(view.stats.draws,1);assert.equal(view.stats.ruins,0);
const intactCount=view.stats.instances;
const [x,z]=site.point(0,-site.depth/2-1.5),y=site.y+1;
const event={type:'explosion',x,y,z,radius:8,maxDamage:100,interiorId:null};
const probe={x,y,z,dx:site.nx,dy:0,dz:site.nz,range:3};
assert(shots.trace(probe)<1.6,'intact station stops solid-world rays');
assert.deepEqual(state.damageExplosion({...event,interiorId:'test-room'},shots.trace),[]);
assert.deepEqual(state.damageExplosion({...event},()=>0),[],'unrelated solid cover blocks blast damage');
assert.equal(site.health,120);
assert.deepEqual(state.damageExplosion(event,shots.trace),[]);
assert(site.health>0&&site.health<60);
const remaining=site.health;
assert.deepEqual(state.damageExplosion(event,shots.trace),[]);
assert.equal(site.health,remaining,'one event cannot damage a post twice');
const [destroyed]=state.damageExplosion({...event},shots.trace);
assert.equal(destroyed.id,site.id);
assert(shots.removeBarrier(destroyed.barrier.id));
assert(!shots.removeBarrier(destroyed.barrier.id));
assert(shots.trace(probe)>2.99,'rays pass through open air above destroyed foundations');
assert(simulation.canOccupy(body,{length:2,width:1}),'destroyed wall leaves no hidden vehicle collider');
assert.equal(state.responseLoss(),1);
assert.equal(state.patrolStations().length,2);
assert(!state.patrolStations().some(post=>post.id===site.id));
view.update(site.approach);
assert.equal(view.stats.ruins,1);assert(view.stats.instances<intactCount);
view.update({x:site.x+3000,z:site.z+3000});assert.equal(view.stats.draws,0);
view.dispose();view.dispose();assert.equal(scene.children.length,0);
console.log('PASS three fictional police posts, culling, cover and event replay, rubble, removed body and shot colliders, reduced police infrastructure',JSON.stringify({placementMilliseconds,locations:state.sites.map(p=>p.place.description)}));
