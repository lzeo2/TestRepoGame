import assert from 'node:assert/strict';
import * as THREE from './vendor/three.module.js';
import {loadCharacter,disposeCharacterAssets} from './character-assets.mjs';
import {createSystems} from './systems.mjs';
import {createSystemsLayer} from './systems-view.mjs';
await loadCharacter('trooper');
const sim=createSystems(),scene=new THREE.Scene(),layer=createSystemsLayer(scene);
sim.step(30);layer.sync(sim);
assert.equal(scene.children.length,24);
const [first,second]=scene.children;
assert.equal(first.userData.model.triangles,31730);
assert.equal(first.userData.model.meshes,12);
const meshes=group=>{const a=[];group.traverse(o=>{if(o.isMesh)a.push(o);});return a;};
assert.equal(meshes(first)[0].geometry,meshes(second)[0].geometry,'GPU geometry shared by squads');
assert.notEqual(meshes(first)[0].material,meshes(second)[0].material,'HP/team material state isolated');
const candle=first.userData.head,y=candle.position.y;
assert.ok(Math.abs(y-1.45)<1e-6);
sim.troopers[0].candleScale=.35;sim.troopers[0].emissiveScale=.35;layer.sync(sim);
assert.equal(candle.scale.y,.35);assert.equal(candle.position.y,y);
assert.equal(first.rotation.y,Math.PI,'Carbon front points toward enemy +Z');
const ally=sim.addHero({id:'team-mate',team:'carbon',position:{x:0,y:0,z:8}});
const enemy=sim.addHero({id:'foe',team:'ivory',position:{x:0,y:0,z:0}});
const camera=new THREE.PerspectiveCamera();camera.rotation.y=.4;layer.sync(sim,camera);
const marker=id=>scene.children.find(o=>o.userData.kind==='hero-marker'&&o.userData.id===id);
assert.ok(marker(ally.id)&&marker(enemy.id));
assert.equal(marker(ally.id).children[0].geometry.parameters.thetaSegments,24,'ally circle differs from enemy diamond');
assert.equal(marker(enemy.id).children[0].geometry.parameters.thetaSegments,4);
assert.ok(marker(ally.id).userData.health.quaternion.angleTo(camera.quaternion)<1e-7);
assert.ok(sim.damage(enemy.id,100,ally.id,{kind:'ability'}).ok);layer.sync(sim,camera);
assert.ok(marker(enemy.id).userData.fill.scale.x<1.4,'real HP controls world health bar');
const npc=sim.troopers.find(t=>t.team==='ivory');
sim.addHero({id:'player',team:'carbon',position:{...npc.position,x:npc.position.x+5}});
sim.step(.05);layer.sync(sim,camera);
assert.ok(scene.children.some(o=>o.userData.kind==='attack-warning'),'actual pending attack has a world cue');
sim.moveHero('player',sim.bases.carbon);sim.step(.05);layer.sync(sim,camera);
assert.ok(!scene.children.some(o=>o.userData.kind==='attack-warning'),'lost target clears its cue');
const material=meshes(first)[0].material;let disposed=0;material.addEventListener('dispose',()=>disposed++);
layer.dispose();layer.dispose();assert.equal(disposed,1);assert.equal(scene.children.length,0);
disposeCharacterAssets();
console.log('systems-view:24 actual31,730-triangle troops, shared geometry, isolated materials, bottom-anchored HP candle, facing and cleanup PASS (CPU only)');
