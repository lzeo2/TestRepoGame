var getPieceValue = function (piece, x, y) {
    if (piece === null) {
        return 0;
    }
    var getAbsoluteValue = function (piece, isWhite, x ,y) {
        if (piece.type === 'p') {
            return 10 + ( isWhite ? pawnEvalWhite[y][x] : pawnEvalBlack[y][x] );
        } else if (piece.type === 'r') {
            return 50 + ( isWhite ? rookEvalWhite[y][x] : rookEvalBlack[y][x] );
        } else if (piece.type === 'n') {
            return 30 + knightEval[y][x];
        } else if (piece.type === 'b') {
            return 30 + ( isWhite ? bishopEvalWhite[y][x] : bishopEvalBlack[y][x] );
        } else if (piece.type === 'q') {
            return 90 + evalQueen[y][x];
        } else if (piece.type === 'k') {
            return 900 + ( isWhite ? kingEvalWhite[y][x] : kingEvalBlack[y][x] );
        }
        throw "Unknown piece type: " + piece.type;
    };

    var absoluteValue = getAbsoluteValue(piece, piece.color === 'w', x ,y);
    return piece.color === 'w' ? absoluteValue : -absoluteValue;
};



self.onmessage = function (event) {
    var data = event.data || {};
    if (data.type !== 'search' || !data.fen) return;

    var searchGame;
    try {
        searchGame = new Chess(data.fen);
    } catch (error) {
        self.postMessage({ type: 'error', requestId: data.requestId, message: 'Could not load this position.' });
        return;
    }

    var moves = searchGame.ugly_moves();
    if (!moves.length) {
        self.postMessage({ type: 'complete', requestId: data.requestId, positions: 0, elapsed: 0 });
        return;
    }

    var toMove = function (move) {
        var prettyMove = searchGame.ugly_move(move);
        searchGame.undo();
        return { from: prettyMove.from, to: prettyMove.to, promotion: prettyMove.promotion || 'q' };
    };
    var started = Date.now();
    var bestMove = toMove(moves[0]);
    positionCount = 0;
    self.postMessage({ type: 'progress', requestId: data.requestId, move: bestMove, depth: 0, positions: 0, elapsed: 0 });

    var maxDepth = Math.max(1, Math.min(5, Number(data.maxDepth) || 3));
    for (var depth = 1; depth <= maxDepth; depth++) {
        var candidate = minimaxRoot(depth, searchGame, true);
        if (!candidate) break;
        bestMove = toMove(candidate);
        self.postMessage({
            type: 'progress',
            requestId: data.requestId,
            move: bestMove,
            depth: depth,
            positions: positionCount,
            elapsed: Date.now() - started
        });
    }
    self.postMessage({
        type: 'complete', requestId: data.requestId, move: bestMove,
        depth: maxDepth, positions: positionCount, elapsed: Date.now() - started
    });
};
