import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Game,SAVE_KEY,MUTATIONS} from '../js/game.js';
const data=JSON.parse(await readFile(new URL('../data/catalog.json',import.meta.url),'utf8'));
class MemoryStorage {
  constructor() { this.values=new Map(); }
  getItem(key) { return this.values.get(key)??null; }
  setItem(key,value) { this.values.set(key,String(value)); }
  removeItem(key) { this.values.delete(key); }
}
let now=600;
const storage=new MemoryStorage();
const game=new Game(data,{storage,clock:()=>now,random:()=>0});
game.nextAttemptAt=Infinity;
const act=(name,payload={},expected=true)=>{ const result=game.action(name,payload); assert.equal(result.ok,expected,result.message); return result; };
assert.equal(game.state.coins,150);
assert.equal(game.state.roster.length,0,'No automatic player grant');
assert.equal(game.state.market.length,5);
assert.equal(game.state.rivals.length,12);
assert.equal(game.team().length,11);
assert.ok(game.team().every(p=>p.borrowed));
act('beginBattle',{},false);
act('developerCode',{code:'wrong'},false);
act('buy',{marketId:'belt-0'});
assert.equal(game.state.coins,100,'Final source starter price is 50');
const starter=game.state.roster[0];
assert.equal(starter.id,'saka');
assert.equal(game.income(),1.2,'Source final income uses 0.6 progression multiplier');
assert.equal(game.team().filter(p=>!p.borrowed).length,1);
const stable=game.stats({...starter,seed:200,level:0,mutationId:'ordinary',traitId:'clinical'});
assert.equal(stable.power,38);
assert.equal(stable.attacking,41.45,'Baseline gets one 8% shooting trait bonus');
assert.equal(stable.pace,41.04);
const base=game.stats({...starter,seed:200,traitId:'clinical'});
for (const mutation of MUTATIONS) {
  const stats=game.stats({...starter,seed:200,traitId:'clinical',mutationId:mutation.id,level:5});
  assert.equal(stats.power,Math.round(base.power*1.15*(1+mutation.powerBonus)*100)/100);
  assert.ok(Math.abs(stats.income-1.2*1.5*(1+mutation.incomeBonus))<1e-9);
}
const initialCoins=game.state.coins;
game.tick(100000);
assert.ok(Math.abs(game.state.coins-initialCoins-.3)<1e-9,'Background delta cannot grant offline cash');
act('upgradePlayer',{uid:starter.uid});
assert.equal(starter.level,1);
assert.ok(Math.abs(game.state.coins-25.3)<1e-9);
act('upgradePlayer',{uid:starter.uid},false);
assert.equal(starter.level,1);
// Detached balance fixtures exercise staff, not a user's wallet.
game.state.coins=20000;
act('hire',{id:'attacking'});
act('assignStaff',{id:'attacking',uid:starter.uid});
assert.equal(game.income(),0);
act('assignStaff',{id:'attacking',uid:starter.uid},false);
act('sell',{uid:starter.uid},false);
act('cancelTraining',{uid:starter.uid});
assert.ok(game.income()>0);
act('assignStaff',{id:'attacking',uid:starter.uid});
assert.equal(starter.staff.attackLevel,0);
now+=120; game.tick(.1);
assert.equal(starter.staff.attackLevel,1);
assert.equal(game.state.staff.assignments.length,0);
act('hire',{id:'fitness'});
starter.staff.injuryUntil=now+180;
act('assignStaff',{id:'attacking',uid:starter.uid},false);
act('assignStaff',{id:'fitness',uid:starter.uid,kind:'injury'});
now+=45; game.tick(.1);
assert.equal(starter.staff.injuryUntil,0);
act('tactics',{formation:'4-3-3',mentality:'pressing',selectedUids:[starter.uid],captainUid:starter.uid});
act('savePreset',{index:3});
act('tactics',{selectedUids:[starter.uid,starter.uid]},false);
act('tactics',{formation:'3-5-2',captainUid:null});
act('loadPreset',{index:3});
assert.equal(game.state.tactics.formation,'4-3-3');
assert.equal(game.state.tactics.captainUid,starter.uid);
act('kit',{enabled:true,name:'LOCAL FC',primary:'#112233',secondary:'#FFFFFF',shorts:'#202020',pattern:'stripes'});
act('kit',{name:'\u0000'},false);
act('egg',{id:'academy'});
assert.equal(game.state.roster.at(-1).level,1);
act('mystery');
assert.equal(game.state.roster.at(-1).level,1);
assert.ok(!game.catalog.get(game.state.roster.at(-1).id).eventOnly);
act('upgradeTeam');
act('upgradeStadium');
assert.equal(game.state.teamUpgrade,1);
assert.equal(game.state.stadiumLevel,1);
act('shopBuy',{id:'incomeBoost'});
assert.ok(Math.abs(game.income()/game.income(true)-1.5)<1e-9);
act('shopBuy',{id:'incomeBoost'},false);
game.state.npcAttempt=null;
const permanentRate=game.income(true);
act('beginBattle');
const frozen=game.state.coins;
game.tick(.25);
assert.equal(game.state.coins,frozen,'Income pauses during squad battles');
act('buy',{marketId:'belt-0'},false);
act('endBattle',{result:{score:[Infinity,0]}},false);
assert.equal(game.state.battleLock,true);
act('endBattle',{result:{score:[2,0],winner:0}});
assert.equal(game.state.lastBattle.reward.incomeRate,permanentRate,'Reward excludes temporary income boost');
assert.equal(game.state.lastBattle.reward.incomeCompensation,Math.round(permanentRate*90*1.25));
assert.equal(game.state.wins,1);
act('endBattle',{result:{score:[2,0]}},false);
act('beginBattle',{},false);
// Carrying reserves the transfer, and requires actual home context to deposit.
game.setLocation({atHome:false,base:0});
const stolen=game.state.rivals[0].roster[0];
act('steal',{base:0,index:0});
assert.equal(game.state.carry.player.uid,stolen.uid);
act('deposit',{},false);
act('upgradeTeam',{},false);
game.setLocation({atHome:true,base:null});
act('deposit');
assert.ok(game.state.roster.some(p=>p.uid===stolen.uid));
assert.equal(game.state.steals,1);
act('buyTool',{id:'baton'});
game.state.npcAttempt={uid:starter.uid,base:0,endsAt:now+12};
act('defend',{tool:'whistle'});
assert.equal(game.state.npcAttempt,null);
act('defend',{tool:'whistle'},false);
now+=8;
game.state.npcAttempt={uid:starter.uid,base:0,endsAt:now+12};
act('shield');
assert.equal(game.state.npcAttempt,null);
act('shield',{},false);
// Current event identity, duplicate claims and limited signings.
now=600; game.currentEvent(); game.state.event.progress=3;
act('eventClaim',{id:game.currentEvent().id});
act('eventClaim',{id:game.currentEvent().id},false);
game.state.eventTokens=100;
act('eventBuy',{id:'ronaldinho',eventId:game.currentEvent().id});
assert.equal(game.state.roster.at(-1).mutationId,'frost');
act('eventBuy',{id:'ronaldinho'},false);
game.save();
const savedCoins=game.state.coins;
now+=100000;
const loaded=new Game(data,{storage,clock:()=>now,random:()=>0});
assert.equal(loaded.state.coins,savedCoins,'Reload never accrues offline income');
assert.deepEqual(loaded.state.roster,game.state.roster);
assert.equal(loaded.state.tactics.presets.length,5);
assert.equal(loaded.state.battleLock,false);
storage.setItem(SAVE_KEY,'{corrupt');
const recovered=new Game(data,{storage,clock:()=>now,random:()=>0});
assert.ok(recovered.saveStatus.includes('recovered backup'));
assert.equal(storage.getItem(SAVE_KEY+':damaged'),'{corrupt');
const denied=new Game(data,{storage:{getItem(){throw new Error('denied');},setItem(){throw new Error('denied');}},clock:()=>now,random:()=>0});
assert.equal(denied.save(),false);
assert.ok(denied.saveStatus.includes('denied'));
const noStorage=new Game(data,{storage:null,clock:()=>now,random:()=>0});
assert.equal(noStorage.save(),false);
assert.equal(noStorage.action('developerCode',{code:'DEVTEAM'}).ok,true);
assert.equal(noStorage.state.coins,150,'Explicit test code preserves coins');
assert.equal(noStorage.state.roster.length,14);
assert.equal(noStorage.team().filter(p=>!p.borrowed).length,11);
assert.equal(noStorage.action('developerCode',{code:'DEVTEAM'}).ok,false);
assert.equal(noStorage.action('tactics',null).ok,false);
assert.equal(noStorage.action('tactics',{formation:'constructor'}).ok,false);
assert.equal(noStorage.action('__proto__',{}).ok,false);
const sameClockStorage=new MemoryStorage();
const first=new Game(data,{storage:sameClockStorage,clock:()=>600,random:()=>0});
first.action('buy',{marketId:'belt-0'});
const again=new Game(data,{storage:sameClockStorage,clock:()=>600,random:()=>0});
assert.equal(again.action('buy',{marketId:'belt-0'}).ok,true);
assert.equal(new Set(again.state.roster.map(p=>p.uid)).size,2,'Stable RNG and same-clock reload cannot duplicate ownership identities');
again.state.coins=50000;
while (again.state.roster.length<18) assert.equal(again.action('egg',{id:'academy'}).ok,true);
const fullBalance=again.state.coins;
assert.equal(again.action('egg',{id:'academy'}).ok,false);
assert.equal(again.state.coins,fullBalance,'Full roster rejects before spending');
again.state.npcAttempt={uid:again.state.roster[0].uid,base:0,endsAt:599};
again.nextAttemptAt=Infinity; again.tick(.1);
assert.equal(again.state.roster.length,17,'Unrepelled NPC theft transfers a recruit');
const defensiveRoster=again.state.roster.length;
again.state.shieldUntil=1000;
again.state.npcAttempt={uid:again.state.roster[0].uid,base:0,endsAt:599}; again.tick(.1);
assert.equal(again.state.roster.length,defensiveRoster,'Shield prevents NPC transfer');
console.log('PASS game: source economy, traits/mutations, training, tactics, kits, market/eggs/mystery, battle locks/reward, steal/deposit, defense, events and local-save recovery');
