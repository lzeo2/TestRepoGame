"""Actual Chromium acceptance through UI inputs, with isolated browser storage.

Run with Python + Playwright installed; serve the repository first.
python tests/browser.py --base http://127.0.0.1:4173/Games/StealFootballer/ \
    --fixture fixture.json --artifacts test-artifacts
The required rich fixture is generated by tests/fixture.mjs using detached Game actions.
"""
import argparse
import json
import time
from pathlib import Path
from playwright.sync_api import sync_playwright, TimeoutError as PlaywrightTimeoutError

parser=argparse.ArgumentParser()
parser.add_argument('--base',default='http://127.0.0.1:4173/Games/StealFootballer/')
parser.add_argument('--fixture',required=True)
parser.add_argument('--artifacts',default='test-artifacts')
parser.add_argument('--quick',action='store_true',help='Skip full-match reward/debrief acceptance explicitly')
parser.add_argument('--low-impact',action='store_true',help='Use low graphics, mute and cap animation callbacks at about 30 fps')
parser.add_argument('--executable-path',help='Use an existing Chromium executable without downloading a browser')
args=parser.parse_args()
artifacts=Path(args.artifacts);artifacts.mkdir(parents=True,exist_ok=True)
fixture=json.loads(Path(args.fixture).read_text(encoding='utf-8-sig'))
checks=[];skipped=[];signature_attempts=[]

def skip(name,reason):
    skipped.append({'check':name,'reason':reason})
    print('SKIP '+name+': '+reason,flush=True)

def configure_context(context):
    if args.low_impact:
        context.add_init_script('''(() => {
          const nativeRAF=window.requestAnimationFrame.bind(window);
          window.requestAnimationFrame=callback=>{
            const requested=performance.now();
            const tick=now=>now-requested>=32?callback(now):nativeRAF(tick);
            return nativeRAF(tick);
          };
        })();''')

def low_impact_settings(page):
    if not args.low_impact:return
    open_panel(page,'help')
    page.locator('#low-graphics').check()
    page.locator('#sound').uncheck()
    close_panel(page)
    page.wait_for_timeout(250)
    check('low-impact settings applied through HELP',snapshot(page)['world']['lowGraphics'] and not snapshot(page)['state']['settings']['sound'])

def keyboard_move(page,name):
    before=snapshot(page)['world']['avatar']
    page.keyboard.down('d');page.wait_for_timeout(700);page.keyboard.up('d')
    after=snapshot(page)['world']['avatar']
    check(name,abs(after['x']-before['x'])>.5)

def check(name,condition):
    assert condition,name
    checks.append(name)
    print('PASS '+name,flush=True)

def snapshot(page):
    return page.evaluate('footballerSnapshot()')

def open_panel(page,name):
    page.locator(f'[data-panel="{name}"]').first.click()
    page.wait_for_timeout(250)

def close_panel(page):
    page.locator('#close-sheet').click()

def activate_signature(page):
    # Availability can expire between the simulation snapshot and a real click.
    # Retry legal opportunities, with ordinary input and an actual cooldown gate.
    deadline=time.monotonic()+30
    attempts=0;last_issue='No legal opportunity observed'
    assert snapshot(page)['match']['cooldowns']['ability']==0,'Signature cooldown must begin at zero'
    while time.monotonic()<deadline:
        current=snapshot(page)['match']
        if current['cooldowns']['ability']>0:
            print(f'INFO signature activated after {attempts} normal click attempts',flush=True)
            return
        if current['finished']:break
        available=next((a for a in current['abilities'] if a['available']),None)
        if available:
            button=page.get_by_role('button',name='Activate '+available['name'],exact=True)
            attempts+=1
            observed={'attempt':attempts,'ability':available['id'],'phase':current['phase'],'elapsed':current['elapsed']}
            signature_attempts.append(observed)
            try:
                button.scroll_into_view_if_needed(timeout=1000)
                visible=button.is_visible();enabled=button.is_enabled();bounds=button.bounding_box()
                observed.update({'visible':visible,'enabled':enabled,'bounds':bounds})
                if not visible or not enabled or not bounds:
                    observed['outcome']='Opportunity changed before pointer input'
                    continue
                x=bounds['x']+bounds['width']/2;y=bounds['y']+bounds['height']/2
                viewport=page.viewport_size
                if viewport and not (0<=x<viewport['width'] and 0<=y<viewport['height']):
                    observed['outcome']='Button centre outside viewport'
                    continue
                # Native pointer input avoids locator stability/navigation waits
                # across the live panel's one-second element replacements.
                page.mouse.click(x,y)
                observed['outcome']='Native pointer click sent'
                last_issue=page.locator('#toast').inner_text()
                observed['feedback']=last_issue
            except PlaywrightTimeoutError as error:
                last_issue=str(error)
                observed['outcome']='Observation/scroll timed out'
                observed['error']=last_issue
        page.wait_for_timeout(100)
    current=snapshot(page)['match']
    raise AssertionError(f'Signature activation never started its cooldown; attempts={attempts}, phase={current["phase"]}, last_issue={last_issue}, observations={json.dumps(signature_attempts)}')

with sync_playwright() as p:
    launch={'headless':True,'args':['--enable-unsafe-swiftshader','--ignore-gpu-blocklist']}
    if args.executable_path:launch['executable_path']=args.executable_path
    browser=p.chromium.launch(**launch)
    errors=[];requests=[]
    context=browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    configure_context(context)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('response',lambda r:requests.append(f'{r.status} {r.url}') if r.status>=400 else None)
    page.goto(args.base,wait_until='networkidle')
    page.locator('#start').wait_for(state='visible')
    page.wait_for_function('!document.getElementById("start").disabled')
    page.locator('#start').click()
    page.wait_for_timeout(500)
    check('fresh club has 150 coins and no automatic grants',snapshot(page)['state']['coins']==150 and not snapshot(page)['state']['roster'])
    check('fresh rivals start at development level zero',snapshot(page)['state']['npcDevelopment']['level']==0 and all(r['development']['rosterTarget']==3 for r in snapshot(page)['state']['rivals']))
    low_impact_settings(page)
    before=snapshot(page)['world']['avatar']
    page.locator('#world').focus();page.keyboard.down('d');page.wait_for_timeout(700);page.keyboard.up('d')
    after=snapshot(page)['world']['avatar']
    check('keyboard movement changes grounded avatar',abs(after['x']-before['x'])>.5)
    page.locator('#home').click()
    check('GO HOME retains actual HUD button focus',page.locator('#home').evaluate('(el)=>document.activeElement===el'))
    keyboard_move(page,'HUD button focus permits keyboard movement')
    open_panel(page,'shop');page.keyboard.press('Escape')
    keyboard_move(page,'Escape menu dismissal permits keyboard movement')
    open_panel(page,'shop');page.locator('[data-action="openMarket"]').click()
    offer=next(m for m in snapshot(page)['state']['market'] if m['id'] in ['saka','yamal','palmer'])
    page.locator(f'[data-action="buy"][data-market="{offer["marketId"]}"]').click()
    check('natural conveyor purchase adds player and spends coins',len(snapshot(page)['state']['roster'])==1 and snapshot(page)['state']['coins']<150)
    uid=snapshot(page)['state']['roster'][0]['uid']
    close_panel(page);open_panel(page,'roster')
    check('roster has real sell and upgrade controls',page.locator('[data-action="sell"]').count()==1 and page.locator('[data-action="upgradePlayer"]').count()==1)
    page.locator('[data-action="sell"]').click()
    check('sell removes recruit and credits value',not snapshot(page)['state']['roster'])
    close_panel(page);page.reload(wait_until='networkidle');page.locator('#start').click()
    check('save reload retains sold roster',not snapshot(page)['state']['roster'] and snapshot(page)['state']['coins']<150)
    context.close()

    # A separate detached rich fixture covers advanced source systems.
    context=browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    configure_context(context)
    context.add_init_script('localStorage.setItem("steal-footballer:v1",'+json.dumps(json.dumps(fixture))+');')
    page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.base,wait_until='networkidle');page.locator('#start').click()
    low_impact_settings(page)
    check('saved active rival development is restored',snapshot(page)['state']['npcDevelopment']['level']==int(fixture.get('npcActiveSeconds',0)//180))
    open_panel(page,'help')
    check('HELP explains rival training and signature skills',page.locator('[data-rival-development]').count()==1 and 'SIGNATURE SKILLS' in page.locator('#sheet-content').inner_text())
    close_panel(page)
    open_panel(page,'tactics')
    check('modal background is inert',page.evaluate('document.getElementById("hud").inert && document.getElementById("world").inert && document.querySelector(".skip").inert'))
    page.locator('#close-sheet').focus();page.keyboard.press('Shift+Tab')
    check('modal backwards Tab wraps to final control',page.locator('[data-action="applyTactics"]').evaluate('(el)=>document.activeElement===el'))
    page.keyboard.press('Tab')
    check('modal forwards Tab wraps to close control',page.locator('#close-sheet').evaluate('(el)=>document.activeElement===el'))
    page.locator('#formation').focus()
    page.locator('#formation').select_option('4-3-3')
    check('tactics select retains focus after rerender',page.locator('#formation').evaluate('(el)=>document.activeElement===el'))
    page.locator('[data-position="1"]').drag_to(page.locator('[data-position="2"]'))
    page.locator('[data-action="applyTactics"]').click()
    check('drag and drop tactics apply source formation; feedback: '+page.locator('#toast').inner_text(),snapshot(page)['state']['tactics']['formation']=='4-3-3')
    if not args.quick:page.screenshot(path=str(artifacts/'desktop-tactics.png'))
    close_panel(page);open_panel(page,'kits')
    page.locator('#kit-name').fill('TEST FC');page.locator('#kit-pattern').select_option('stripes')
    page.locator('#kit-primary').fill('#a52f43');page.locator('[data-action="saveKit"]').click()
    check('custom kit is saved and enabled',snapshot(page)['state']['kit']['enabled'] and snapshot(page)['state']['kit']['name']=='TEST FC' and snapshot(page)['state']['kit']['pattern']=='stripes')
    close_panel(page);open_panel(page,'staff')
    page.locator('[data-action="hire"][data-id="attacking"]').click()
    check('coach hire records actual staff ownership','attacking' in snapshot(page)['state']['staff']['owned'])
    page.locator('[data-action="assignStaff"][data-id="attacking"]').click()
    check('individual training assignment suppresses that income',len(snapshot(page)['state']['staff']['assignments'])==1)
    page.locator('[data-action="cancelTraining"]').click()
    check('training can be cancelled',not snapshot(page)['state']['staff']['assignments'])
    close_panel(page);page.locator('#pitch').click();open_panel(page,'upgrades')
    page.locator('[data-action="upgradeStadium"]').click()
    check('stadium upgrade at real home venue',snapshot(page)['state']['stadiumLevel']==1)
    close_panel(page);open_panel(page,'events');check('limited event objective and offers render',page.locator('[data-action="eventClaim"]').count()==1)
    close_panel(page);page.locator('#battle').click();page.wait_for_timeout(2000)
    s=snapshot(page)
    check('battle has 22 positioned players',len(s['match']['players'])==22)
    check('income pauses during battle',s['state']['battleLock'] and page.locator('#income').inner_text()=='PAUSED')
    coins=s['state']['coins'];page.wait_for_timeout(1500)
    check('battle earns no passive income',snapshot(page)['state']['coins']==coins)
    page.locator('#follow').select_option('9');page.locator('#next').click();page.locator('#zoom-in').click()
    check('specific-player spectator and zoom',snapshot(page)['world']['camera']['mode']=='player' and snapshot(page)['world']['camera']['zoom']>.85)
    page.locator('#follow').select_option('ball')
    page.screenshot(path=str(artifacts/'desktop-match.png'))
    page.locator('[data-action="play"][data-id="throughBall"]').click()
    page.wait_for_timeout(1000)
    check('players move dynamically',any(abs(a['x']-b['x'])>.1 or abs(a['z']-b['z'])>.1 for a,b in zip(s['match']['players'],snapshot(page)['match']['players'])))
    open_panel(page,'match');check('superstar abilities and Icon controls are present',page.locator('[data-action="ability"]').count()>0 and page.locator('[data-action="controlIcon"]').count()>0)
    abilities=snapshot(page)['match']['abilities']
    check('all twelve signature definitions reach the match UI',len(abilities)==12 and all(a.get('description') and a.get('cost') and a.get('duration') for a in abilities))
    check('signature cards explain stamina and legal opportunities','stamina' in page.locator('#sheet-content').inner_text() and 'Anticipation' in page.locator('#sheet-content').inner_text())
    activate_signature(page)
    check('normal signature button starts its cooldown',snapshot(page)['match']['cooldowns']['ability']>0)
    page.locator('#sheet-content [data-action="openSubs"]').focus()
    page.wait_for_timeout(1200)
    check('live match refresh preserves focused action identity',page.locator('#sheet-content [data-action="openSubs"]').evaluate('(el)=>document.activeElement===el'))
    page.screenshot(path=str(artifacts/'signature-skills.png'))
    close_panel(page);open_panel(page,'subs');check('bench and substitutions exist',page.locator('[data-action="substitute"]').count()>0)
    close_panel(page)
    if args.quick:
        skip('completed match pays one scaled reward and unlocks income','--quick omits the unmodified full-match wait')
        skip('debrief includes possession and shots','--quick does not complete a match or accept its debrief')
    else:
        # Let an actual unmodified match finish, including optional extra time/shootout.
        page.wait_for_function('footballerSnapshot().match.finished',timeout=360000,polling=1000)
        s=snapshot(page)
        check('completed match pays one scaled reward and unlocks income',s['report'] is not None and not s['state']['battleLock'] and s['state']['lastBattle']['reward']['total']>0)
        check('debrief includes possession and shots',page.locator('.stats-table').count()==1 and 'Possession' in page.locator('#sheet-content').inner_text())
        page.screenshot(path=str(artifacts/'desktop-debrief.png'))
        page.locator('[data-action="leaveMatch"]').click()
    open_panel(page,'help');page.locator('#low-graphics').check()
    close_panel(page);check('low graphics changes renderer',snapshot(page)['world']['lowGraphics'])
    check('no browser exceptions or missing assets',not errors and not requests)
    context.close()

    mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=1)
    configure_context(mobile)
    page=mobile.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.base,wait_until='networkidle');page.locator('#start').click()
    low_impact_settings(page)
    check('mobile touch controls visible',page.locator('#joystick').is_visible())
    # Chromium CDP dispatches native touch input, never mouse emulation.
    try:
        touch=mobile.new_cdp_session(page)
    except Exception as error:
        skip('native touch joystick moves avatar','HOLD: CDP touch session unavailable: '+str(error))
    else:
        bounds=page.locator('#joystick').bounding_box()
        x=bounds['x']+bounds['width']/2;y=bounds['y']+bounds['height']/2
        before=snapshot(page)['world']['avatar']
        try:
            touch.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y,'id':1}]})
            touch.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x+35,'y':y,'id':1}]})
            page.wait_for_timeout(800)
        finally:
            touch.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
            touch.detach()
        after=snapshot(page)['world']['avatar']
        check('native touch joystick moves avatar',abs(after['x']-before['x'])>.5)
    page.screenshot(path=str(artifacts/'mobile-world.png'))
    for name in ['shop','tactics','kits','staff','events','help']:
        open_panel(page,name)
        check('mobile '+name+' screen fits viewport',page.locator('#sheet').bounding_box()['width']<=390)
        if name=='kits' and not args.quick:page.screenshot(path=str(artifacts/'mobile-kits.png'))
        close_panel(page)
    check('no mobile page overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('no mobile exceptions',not errors)
    mobile.close();browser.close()

(artifacts/'browser-results.json').write_text(json.dumps({'mode':'quick' if args.quick else 'full','lowImpact':args.low_impact,'checks':checks,'skipped':skipped,'signatureAttempts':signature_attempts,'errors':errors,'failedRequests':requests},indent=2),encoding='utf-8')
print(f'{len(checks)} browser acceptance checks passed; {len(skipped)} skipped',flush=True)
